"""test_bench_scoring.py - THE SCORING PARITY GATE (Phase 2 gate a).

WHAT THIS TEST PROVES, AND WHAT IT DOES NOT. Stated first, because a parity claim that overstates
its coverage is worse than no parity claim.

PROVED. The ported scorer (``atlas.bench.scoring``) and the v1 scorer
(``scripts/reconstruction_bench.py``, which produced the numbers the deck serves) return
IDENTICAL verdicts on 288 recoverable inputs: 220 randomized cases exercising the window=None
path, the sliding proximity path, any-of atom groups, and every branch of the normalizer
(digit-group commas, the six-member dash family plus the minus sign, emphasis marks, JSON
escapes, tabs, casefold, whitespace collapse), plus the 18 frozen v1 atom sets replayed against
hit / tight / miss / far haystacks. Both the boolean and the first-hit OFFSET must agree - an
offset is a position in the normalized string, so an offset match is a normalizer match. The
normalizer is also compared directly, output string against output string.

NOT PROVED, and not claimable by anyone. The 2026-07-28 run cannot be replayed row by row:
``evidence/reconstruction_bench_2026-07-28/rows.json`` banks each row's verdict, cost and offset
but NOT the arm context that produced it, so the scorer's actual inputs for that run no longer
exist. ``test_the_banked_rows_carry_no_contexts`` asserts that absence mechanically rather than
leaving it as a sentence in a docstring - if a future bundle ever does bank contexts, that test
fails and this file gains the replay it currently cannot have.

The fixture is DATA, generated by ``scripts/gen_bench_scoring_parity_fixture.py`` running the OLD
scorer. atlas imports nothing from laplace to make this comparison - the seal carries no code,
here as everywhere.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from atlas.bench.scoring import (
    LIVE_GIT_SENTINEL,
    atom_positions,
    normalize,
    score,
)

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "scoring_parity_2026-07-28.json"
V1_ROWS = (Path(__file__).resolve().parents[2] / "evidence"
           / "reconstruction_bench_2026-07-28" / "rows.json")


@pytest.fixture(scope="module")
def fixture():
    if not FIXTURE.is_file():
        pytest.skip(f"parity fixture absent: regenerate with "
                    f"python3 scripts/gen_bench_scoring_parity_fixture.py ({FIXTURE})")
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_fixture_covers_both_verdicts(fixture):
    """A parity fixture where everything scores True proves only that nothing raised."""
    rows = fixture["score_cases"]
    assert len(rows) >= 200, "the parity fixture must carry at least 200 cases"
    correct = sum(1 for r in rows if r["v1_correct"])
    assert 0 < correct < len(rows), "the fixture must contain both correct and incorrect cases"


def test_normalizer_is_byte_identical(fixture):
    for case in fixture["normalize_cases"]:
        assert normalize(case["raw"]) == case["v1_normalized"], case["raw"]


def test_score_verdicts_are_identical(fixture):
    mismatches = []
    for case in fixture["score_cases"]:
        correct, offset = score(case["context"], case["atoms"], case["window"])
        if bool(correct) != case["v1_correct"] or offset != case["v1_first_hit_offset"]:
            mismatches.append({
                "case_id": case["case_id"], "atoms": case["atoms"], "window": case["window"],
                "v1": (case["v1_correct"], case["v1_first_hit_offset"]),
                "v2": (bool(correct), offset),
            })
    assert mismatches == [], f"{len(mismatches)} parity mismatches, first: {mismatches[:2]}"


def test_normalized_length_agrees(fixture):
    """A weaker check than the verdict, but it localises a normalizer drift to the length."""
    for case in fixture["score_cases"]:
        assert len(normalize(case["context"])) == case["v1_normalized_len"], case["case_id"]


def test_the_banked_rows_carry_no_contexts():
    """The mechanical form of 'row-level replay is impossible'. Asserted, not described."""
    if not V1_ROWS.is_file():
        pytest.skip(f"the 2026-07-28 bundle is not in this tree ({V1_ROWS})")
    data = json.loads(V1_ROWS.read_text(encoding="utf-8"))
    rows = data["rows"]
    assert rows, "the banked run has no rows"
    with_context = [r for r in rows if "context" in r]
    assert with_context == [], (
        "the banked 2026-07-28 rows now carry contexts - row-level scoring parity has become "
        "possible and this test file should gain it")
    # The fields that ARE banked, named so a future reader knows what was available.
    assert {"task", "class", "arm", "correct", "first_hit_offset"} <= set(rows[0])


# --- the ported helpers, exercised directly --------------------------------

def test_atom_positions_caps_at_200():
    hay = normalize("ab " * 500)
    assert len(atom_positions(hay, "ab")) == 200


def test_any_of_group_needs_one_member():
    assert score("the value is 83.5%", [["0.835", "83.5%"]], None)[0] is True
    assert score("the value is 0.9", [["0.835", "83.5%"]], None)[0] is False


def test_window_is_a_sliding_check_not_a_first_position_check():
    """Two atoms far apart at first occurrence but close at a later one still pass."""
    ctx = "alpha " + "x " * 400 + "beta alpha"
    assert score(ctx, ["alpha", "beta"], 20)[0] is True
    assert score(ctx, ["alpha", "beta"], 2)[0] is False


def test_digit_group_commas_and_dashes_normalize_together():
    assert normalize("12,335 a—b") == normalize("12335 a-b")


def test_live_git_sentinel_constant_is_ported():
    """v2 has no live-git task; the guard is ported so behaviour is bit-identical."""
    assert LIVE_GIT_SENTINEL == "__LIVE_GIT__"
