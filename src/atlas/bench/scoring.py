"""scoring.py - the v1 scorer, ported. Same normalizer, same atoms, same window, same leak test.

PORTED VERBATIM from ``scripts/reconstruction_bench.py`` (the 2026-07-28 run): ``normalize``,
``atom_positions``, ``score`` and ``assert_no_leak`` are the same algorithms, character for
character in their bodies. That matters because the deck's served numbers were produced by those
functions; if v2 scored differently, every comparison against the banked run would be a
comparison of two instruments rather than of two arms.

ONE deliberate difference, and it changes no verdict: ``assert_no_leak`` raised ``SystemExit`` in
the script and raises ``LeakageDetected`` here, so a test can assert the refusal's identity
instead of an exit code. Detection - which patterns fire, on which atoms - is untouched.

What the parity test covers is stated where the test lives (``atlas/tests/test_bench_scoring.py``)
and in ``atlas/tests/fixtures/README.md``: the banked ``rows.json`` of 2026-07-28 stores verdicts
but NOT the arm contexts that produced them, so a row-level replay is impossible. Parity is
therefore proved on inputs that are recoverable - a fixture of randomized cases generated by
running the OLD scorer, plus the 18 frozen atom sets - and the absence of contexts in the banked
rows is asserted mechanically rather than claimed in prose.

The normalizer is load-bearing and identical for every arm. An arm that normalized its own text
differently would be scored on a different string than its competitors.
"""

from __future__ import annotations

import re
from collections import defaultdict

from ..errors import LeakageDetected

#: Identity of this scorer. Folded into ``bundle_id``: changing the normalizer changes the
#: ground truth, so it must change the bundle it can be replayed against.
SCORING_VERSION = "bench-scoring/2026-07-28-port"

#: The v1 sentinel for the live-git task. Bench v2 has no live-git task - a frozen snapshot has
#: no working tree - but the guard is ported so the function's behaviour is bit-identical.
LIVE_GIT_SENTINEL = "__LIVE_GIT__"

#: The atom-position cap of v1. A needle occurring more than this many times contributes only its
#: first 200 positions to the window search.
POSITION_CAP = 200


def normalize(text: str) -> str:
    """The shared normalizer - identical for every arm (load-bearing, v1 risk R3).

    JSON-unescape, strip emphasis marks, strip digit-group commas, unify the dash family,
    collapse whitespace, casefold. Ported unchanged.
    """
    t = text.replace("\\n", "\n").replace("\\t", "\t").replace('\\"', '"')
    t = t.replace("*", "").replace("`", "")
    t = re.sub(r"(?<=\d),(?=\d{3})", "", t)
    t = re.sub(r"[‐-―−]", "-", t)
    t = re.sub(r"\s+", " ", t)
    return t.casefold()


def atom_positions(hay: str, needle: str, cap: int = POSITION_CAP) -> list[int]:
    """Every position of ``needle`` in an ALREADY-NORMALIZED haystack, up to ``cap``. Ported."""
    out: list[int] = []
    start = 0
    n = normalize(needle)
    while len(out) < cap:
        i = hay.find(n, start)
        if i < 0:
            break
        out.append(i)
        start = i + 1
    return out


def score(context: str, atoms: list, window: int | None) -> tuple[bool, int | None]:
    """All must-atoms present (any-of groups by one member), within ``window`` if set. Ported.

    Returns ``(correct, first_hit_offset)`` - the offset is the position of the LAST atom to
    appear, which is how deep into the arm's context the answer finally completes.
    """
    hay = normalize(context)
    per_atom: list[list[int]] = []
    for atom in atoms:
        members = atom if isinstance(atom, list) else [atom]
        pos: list[int] = []
        for m in members:
            pos.extend(atom_positions(hay, m))
        if not pos:
            return False, None
        per_atom.append(sorted(pos))
    if window is None:
        return True, max(p[0] for p in per_atom)
    # sliding check: does some choice of one position per atom fit in the window
    events = sorted((p, i) for i, ps in enumerate(per_atom) for p in ps)

    lo = 0
    counts: dict[int, int] = defaultdict(int)
    covered = 0
    for hi in range(len(events)):
        p, i = events[hi]
        if counts[i] == 0:
            covered += 1
        counts[i] += 1
        while events[hi][0] - events[lo][0] > window:
            q, j = events[lo]
            counts[j] -= 1
            if counts[j] == 0:
                covered -= 1
            lo += 1
        if covered == len(per_atom):
            return True, events[hi][0]
    return False, None


def assert_no_leak(pattern: str, atoms: list, task_id: str, question: str) -> None:
    """A pattern word occurring in a must-atom but NOT in the question was derived from the
    answer - the baseline would be rigged. Ported; the refusal is named instead of SystemExit."""
    q = question.casefold()
    chunks = re.findall(r"[a-z0-9][a-z0-9_./-]{3,}", pattern.casefold())
    for atom in atoms:
        for m in atom if isinstance(atom, list) else [atom]:
            if m == LIVE_GIT_SENTINEL:
                continue
            am = m.casefold()
            for chunk in chunks:
                if chunk in am and chunk not in q:
                    raise LeakageDetected(
                        "a derived pattern word occurs in a must-atom but not in the question - "
                        "answer-derived pattern, the baseline would be rigged",
                        task_id=task_id, pattern_word=chunk, atom=m,
                    )


def atom_members(atom) -> list[str]:
    """The members of one atom entry: a literal is one member, an any-of group is its list."""
    return list(atom) if isinstance(atom, list) else [atom]


def flatten_atoms(atoms: list) -> list[str]:
    """Every literal string in an atom list, any-of groups flattened. Used by the tripwire."""
    out: list[str] = []
    for atom in atoms:
        out.extend(atom_members(atom))
    return out
