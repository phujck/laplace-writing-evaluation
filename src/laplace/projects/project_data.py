HEX = re.compile(r"[0-9a-f]{64}\Z")
PRIVATE = {".git", ".ssh", ".codex", ".claude", "soul", "soul_dump", "soul_corpus", "soul_vectors", "private", "raw_calibration", "provider_transcripts", ".provider-events"}
CACHES = {"__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", "node_modules", ".venv", ".lake", ".research_previews"}
SECRET_NAMES = {"id_rsa", "id_ed25519", "credentials.json", "auth.json", ".claude.json", ".mcp.json"}
MAX_JSON = 64 * 1024 * 1024
HOME_MARKER = ".writing-project-home.json"
class ManifestError(ValueError):
    pass


def _sha(raw: bytes) -> str:
    return "sha256:" + hashlib.sha256(raw).hexdigest()


def _safe(root: Path, relative: str) -> Path:
    rel = Path(relative)
    if not relative or rel.is_absolute() or ".." in rel.parts:
        raise ManifestError(f"unsafe relative path: {relative}")
    path = root
    for part in rel.parts:
        path = path / part
        if path.is_symlink():
            raise ManifestError(f"symlink input refused: {relative}")
    if not path.resolve().is_relative_to(root):
        raise ManifestError(f"path escapes repo: {relative}")
    return path


def _excluded(relative: Path) -> bool:
    return (bool(set(relative.parts) & (PRIVATE | CACHES)) or relative.name in SECRET_NAMES
            or relative.name == ".env" or relative.name.startswith(".env.")
            or relative.suffix in {".pem", ".key", ".pyc"}
            or relative.suffix == ".lock" and relative.name not in {"uv.lock", "poetry.lock"})


def _files(root: Path, relative: str, suffix: str | None = None, *, max_files=None, extra_excluded=(), max_directories=None) -> list[Path]:
    base = _safe(root, relative)
    if not base.exists():
        return []
    def candidates():
        if base.is_file():
            yield base
        else:
            walked = 0
            for directory, dirs, files in os.walk(base, followlinks=False):
                walked += 1
                if max_directories is not None and walked > max_directories:
                    raise ManifestError("project directory scan budget exceeded")
                for name in list(dirs):
                    path = Path(directory) / name
                    if _excluded(path.relative_to(root)) or set(path.relative_to(root).parts) & set(extra_excluded):
                        dirs.remove(name)
                    else:
                        _safe(root, path.relative_to(root).as_posix())
                for name in files:
                    yield Path(directory) / name
    result = []
    for path in candidates():
        rel = path.relative_to(root)
        if _excluded(rel) or set(rel.parts) & set(extra_excluded) or (suffix and path.suffix != suffix):
            continue
        result.append(_safe(root, rel.as_posix()))
        if max_files is not None and len(result) > max_files:
            raise ManifestError("project file budget exceeded")
    return sorted(set(result))


def home_marker(project: str, directory: str) -> bytes:
    """The exact generated marker bytes for one project home (deterministic, so re-exports reproduce them)."""
    value = {"schema": "laplace.writing-project-home/1", "project": project, "project_dir": directory,
             "derivation": "Generated by the evaluation export. This registered project home held no exportable authored "
                           "file, so this marker keeps the directory through Git and ZIP. It is not a plan, reference, "
                           "research record or source; the authored metadata status stays as recorded."}
    return (json.dumps(value, indent=1, sort_keys=True, ensure_ascii=False) + "\n").encode()


def _project_files(root: Path, project: str, directory: str, selected_dirs: dict | None = None, *, max_files=None, extra_excluded=(), max_directories=None) -> list[Path]:
    """The authored files of one project home: the walk, minus generated home markers (empty-home repair1 EH-R1).

    The only admissible bytes at ``<home>/HOME_MARKER`` are ``home_marker(owner, home)`` where ``owner`` is the SELECTED
    project the registry places at that home (this project, or another selected project whose home is nested here);
    the marker's own content is never authority. They are compared exactly (size, then bytes; no parsing). A marker
    name that is not a regular file, a directory of that name anywhere in the home, or any other bytes refuse before
    anything is copied. Ordinary nested content is never reclassified."""
    owners = {home: name for name, home in (selected_dirs or {}).items()}
    owners[directory] = project
    reserved = root / directory / HOME_MARKER
    if reserved.is_symlink() or (reserved.exists() and not reserved.is_file()):
        raise ManifestError("the reserved project-home marker path is not a regular file: " + directory + "/" + HOME_MARKER)
    kept = []
    for path in _files(root, directory, max_files=max_files, extra_excluded=extra_excluded, max_directories=max_directories):
        rel = path.relative_to(root)
        if HOME_MARKER in rel.parts[:-1]:
            raise ManifestError("a directory uses the reserved project-home marker name: " + rel.as_posix())
        if path.name != HOME_MARKER:
            kept.append(path)
            continue
        parent = rel.parent.as_posix()
        owner = owners.get(parent)
        expected = home_marker(owner, parent) if owner else None
        if (expected is None or not path.is_file() or path.stat().st_size != len(expected)
                or path.read_bytes() != expected):
            raise ManifestError("a file at the reserved project-home marker path is not the generated marker of the "
                                "selected project registered at that home: " + rel.as_posix())
    return kept


def _file_record(root: Path, path: Path) -> dict:
    path = _safe(root, path.relative_to(root).as_posix())
    before = path.stat()
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    after = path.stat()
    if (before.st_ino, before.st_size, before.st_mtime_ns, before.st_ctime_ns) != (after.st_ino, after.st_size, after.st_mtime_ns, after.st_ctime_ns):
        raise ManifestError(f"input changed while hashing: {path.relative_to(root)}")
    return {"path": path.relative_to(root).as_posix(), "bytes": after.st_size,
            "sha256": "sha256:" + digest.hexdigest()}


def _json(path: Path):
    with path.open("rb") as stream:
        raw = stream.read(MAX_JSON + 1)
    if len(raw) > MAX_JSON:
        raise ManifestError(f"JSON input exceeds bounded size: {path.name}")
    return json.loads(raw)


def _rows(root: Path, relative: str, *, max_bytes=None, max_rows=None):
    path = _safe(root, relative)
    if not path.exists():
        return []
    result = []; spent = 0
    with path.open("rb") as stream:
        for number, line in enumerate(stream, 1):
            spent += len(line)
            if (max_bytes is not None and spent > max_bytes) or (max_rows is not None and number > max_rows):
                raise ManifestError("ledger scan budget exceeded: " + relative)
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except (ValueError, UnicodeDecodeError) as exc:
                raise ManifestError(f"malformed journal row: {relative}:{number}") from exc
            if not isinstance(row, dict):
                raise ManifestError(f"journal row must be an object: {relative}:{number}")
            result.append((relative, number, line, row))
    return result


def _belongs(row: dict, project: str) -> bool:
    return row.get("project", row.get("corpus")) == project


def _journal_store_key(root: Path, value, recorded_roots=()) -> str | None:
    """Match a recorded store address without rewriting its historical bytes.

    Some existing writers bank absolute paths. Only the exact selected root, or an original root this checkout's
    VERIFIED published export lineage records (published_lineage), can supply their relative identity; another checkout
    is never inferred by suffix. The result must still equal an exact selected ledger file plus row id at the caller.
    This is lexical matching, not a filesystem read of the original host.
    """
    if not isinstance(value, str) or not value:
        return None
    path = Path(value)
    if ".." in path.parts:
        return None
    if path.is_absolute():
        for base in (root, *recorded_roots):
            try:
                return path.relative_to(base).as_posix()
            except ValueError:
                continue
        return None
    return path.as_posix()


def _row_record(item) -> dict:
    path, number, raw, row = item
    return {"file": path, "line": number, "id": row.get("id"), "record": row.get("record"),
            "act_id": row.get("act_id"), "bytes": len(raw), "row_sha256": _sha(raw)}


def _typed_refs(value):
    if isinstance(value, dict):
        if is_public_body_reference(value):
            yield value
        else:
            for child in value.values():
                yield from _typed_refs(child)
    elif isinstance(value, list):
        for child in value:
            yield from _typed_refs(child)


def _body_closure(root: Path, values: list, *, max_files=None, max_bytes=None) -> tuple[list, list, list]:
    queue = [ref for value in values for ref in _typed_refs(value)]
    records, missing, unresolved, seen = [], [], [], set()
    while queue:
        ref = queue.pop()
        try:require_public_body_reference(ref)
        except ValueError as exc:
            unresolved.append({"reference": ref, "reason": str(exc)})
            continue
        handle = ref.get("content_handle", "")
        digest = handle.removeprefix("sha256:") if isinstance(handle, str) else ""
        if not HEX.fullmatch(digest):
            raise ManifestError("malformed typed public-body handle")
        # The repository copy is the sole permitted closure, including legacy
        # records whose original store was external. Never consult shared state.
        if digest in seen:
            continue
        seen.add(digest)
        relative = f"contract/writing_bodies/{digest[:2]}/{digest}"
        path = _safe(root, relative)
        if not path.is_file():
            missing.append({"content_handle": handle, "required_repository_path": relative,
                            "recorded_store": ref.get("store")})
            continue
        item = _file_record(root, path)
        if type(ref.get("bytes")) is not int or item["bytes"] != ref["bytes"]:
            raise ManifestError(f"public-body declared size mismatch: {relative}")
        if item["sha256"] != "sha256:" + digest:
            raise ManifestError(f"public-body hash mismatch: {relative}")
        if max_files is not None and len(records) + 1 > max_files:
            raise ManifestError("body file budget exceeded")
        if max_bytes is not None and sum(r["bytes"] for r in records) + item["bytes"] > max_bytes:
            raise ManifestError("body byte budget exceeded")
        records.append(item)
        try:
            queue.extend(_typed_refs(_json(path)))
        except (ValueError, UnicodeDecodeError) as exc:
            unresolved.append({"path": relative, "reason": f"body cannot be inspected as JSON: {type(exc).__name__}"})
    return sorted(records, key=lambda row: row["path"]), missing, unresolved



def select_history(root, project, *, talk=None, journal=None, recorded_roots=(), additional=(), read_rows=None, with_lineage=False):
    """Shared exact selection; relocated addresses admit only proven retained rows."""
    read_rows = read_rows or _rows
    retained, inherited = retained_history(root, project, read_rows=read_rows)
    talk = read_rows(root, 'contract/talk.jsonl') if talk is None else talk
    selected = [item for item in talk if _belongs(item[3], project)]
    sessions = {r[3].get('session_id') for r in selected} | {r[3].get('id') for r in selected if r[3].get('record') == 'writing-session'}
    turns = {r[3].get('turn_id') for r in selected} | {r[3].get('id') for r in selected if r[3].get('record') == 'writing-turn'}
    sessions.discard(None); turns.discard(None)
    kept = {id(r) for r in selected}
    selected.extend(r for r in talk if id(r) not in kept and not r[3].get('project', r[3].get('corpus'))
                    and (r[3].get('session_id') in sessions or r[3].get('turn_id') in turns))
    for path in [f'corpus_friction/{project}.jsonl', 'corpus_friction/work_orders.jsonl']:
        selected.extend(r for r in read_rows(root, path) if path.endswith('/' + project + '.jsonl') or _belongs(r[3], project))
    selected.extend(additional)
    row_ids = {(r[0], r[3].get('id')) for r in selected if r[3].get('id')}
    journal = read_rows(root, 'contract/journal.jsonl') if journal is None else journal
    # Prior roots are NOT a blanket alias for newly encountered journal rows.
    banks = [r for r in journal if (_journal_store_key(root, r[3].get('store')), r[3].get('row_id')) in row_ids]
    acts = {r[3].get('act_id') for r in banks}
    selected.extend(banks)
    selected.extend(r for r in journal if r[3].get('record') in {'act', 'act_end'} and r[3].get('act_id') in acts)
    selected.extend(retained)
    unique = {}
    for row in selected:
        key = row[0], row[1]
        if key in unique and unique[key][2] != row[2]:
            _lineage_error('current and retained row bytes disagree')
        unique[key] = row
    # Preserve the legacy selection order when no retained certificate exists.
    selected = list(unique.values())
    associations = _bank_associations(root, project, selected, inherited)
    needed = sorted((a for a in associations.values() if _journal_store_key(root, a['source_store']) != a['store']), key=lambda a: a['row_sha256'])
    return (selected, needed) if with_lineage else selected


def collect_definitions(root, project, *, read_rows=None, max_rows=None, max_bytes=None, references=None, caller=None):
    """One project-owned WDEF collector for both distribution and data-only policies.

    Transfer structure/chain/receipt validation stays entirely at pipeline.workflow.
    The exact original ledger rows and canonical body bytes travel unchanged.
    """
    if references==[]:return [],[],[]
    if references is not None:
        from laplace.pipeline import workflow_definitions as D
        from laplace.work import owner_discovery as O
        if not isinstance(caller,O.Scope) or not caller.admits(project):raise ManifestError('Selected definition caller is not admitted.')
        requested={}
        for ref in references:
            ident,version=D._selector({'reference':ref},strict=True)
            if version is None:raise ManifestError('Selected definition requires an exact version.')
            if ident in requested:raise ManifestError('Selected definition identity is duplicated.')
            requested[ident]=ref
        selected=[];packages=[];bodies={};spent=0
        for ident,ref in sorted(requested.items()):
            result=D.capture_export(root,caller,ref,max_rows=None if max_rows is None else max_rows-len(selected),
                max_bytes=None if max_bytes is None else max_bytes-spent,transfer_project=project)
            package=result['package'];spent+=len(D.W.canonical(package));packages.append(package);selected.extend(result['rows'])
            if max_rows is not None and len(selected)>max_rows or max_bytes is not None and spent>max_bytes:raise ManifestError('Selected definition budget exceeded.')
            for version in package['versions']:
                row=version['row'];digest=row['body_handle'].removeprefix('sha256:');relative='contract/writing_bodies/'+digest[:2]+'/'+digest
                record=_file_record(root,_safe(root,relative))
                if record['sha256']!=row['body_handle']:raise ManifestError('definition body changed: '+relative)
                bodies[relative]=record
        return sorted(selected,key=lambda r:r[1]),sorted(bodies.values(),key=lambda r:r['path']),packages
    read_rows = read_rows or _rows
    selected = [r for r in read_rows(root, 'contract/dispatches.jsonl')
                if r[3].get('record') == 'workflow-definition' and r[3].get('scope') == {'kind': 'project', 'namespace': project}]
    if max_rows is not None and len(selected) > max_rows:
        raise ManifestError("definition row budget exceeded")
    if not selected and not references:
        return [], [], []
    from laplace.pipeline import workflow_definitions as D
    from laplace.work import owner_discovery as O
    packages, bodies = [], {}
    for ident in sorted({r[3]['definition_id'] for r in selected}):
        package = D.validate_export(D.read(root, O.project_scope(project,'sdk'), {'definition_id':ident,'facet':'export'}))
        if max_bytes is not None and sum(len(D.W.canonical(p)) for p in [*packages, package]) > max_bytes:
            raise ManifestError("definition byte budget exceeded")
        packages.append(package)
        for version in package['versions']:
            row = version['row'];digest = row['body_handle'].removeprefix('sha256:')
            relative = 'contract/writing_bodies/' + digest[:2] + '/' + digest
            record = _file_record(root, _safe(root, relative))
            if record['sha256'] != row['body_handle']:
                raise ManifestError('definition body changed: ' + relative)
            bodies[relative] = record
    return selected, sorted(bodies.values(), key=lambda r: r['path']), packages


PUBLISHED_EXPORT_SCHEMAS = ("laplace.writing-evaluation-export/1", "laplace.writing-evaluation-export/2")

def published_admission(root: Path) -> dict | None:
    """The ONE admission of a published export's metadata (history store relocation repair1 HS-R1), shared by
    published_lineage and the exporter's published aliases; None when ``root`` has no portability index.

    In order, before any metadata byte is read: every metadata path passes the repository fence (_safe: no symlink, no
    escape); the portability index passes its own owner (writing_portability.source_path: schema
    laplace.writing-portability/1 and its unchanged 4 MiB guard); the export report has a known schema; then the
    index, report and source manifest must agree by pin. The source manifest keeps the generic 64 MiB JSON bound."""
    candidate = root / "writing-portability.json"
    if not (candidate.exists() or candidate.is_symlink()):
        return None
    portable = _safe(root, "writing-portability.json")
    report_path = _safe(root, "release/export-manifest.json")
    source_path = _safe(root, "release/source-manifest.json")
    from laplace.projects import writing_portability
    try:
        writing_portability.source_path(".", root)
    except ValueError as exc:
        raise ManifestError("published portability index refused by its owner: " + str(exc)[:200]) from exc
    try:
        report = _json(report_path)
        index = _json(portable)
    except (OSError, ValueError) as exc:
        raise ManifestError("a portability index without its readable published export manifests: " + str(exc)[:200]) from exc
    if not isinstance(report, dict) or report.get("schema") not in PUBLISHED_EXPORT_SCHEMAS:
        raise ManifestError("unknown published export manifest")
    pins = {}
    for row in report.get("copied_files", []) + report.get("derived_files", []):
        if pins.setdefault(row["path"], row) != row:
            raise ManifestError("conflicting published file pins: " + row["path"])
    source_pin = _file_record(root, source_path)["sha256"]
    if (source_pin != report.get("source_manifest_sha256") or source_pin != index.get("source_manifest_sha256")
            or _file_record(root, portable)["sha256"] != (pins.get("writing-portability.json") or {}).get("sha256")):
        raise ManifestError("published portability provenance changed")
    return {"index": index, "report": report, "pins": pins, "source_path": source_path, "source_manifest_sha256": source_pin}


def published_lineage(root: Path) -> dict | None:
    """The verified published export this checkout IS, or None for an ordinary source checkout (history store
    relocation, 2026-10-16). Admitted by published_admission; returns the original checkout roots it records as
    identity directory aliases (absolute spellings mapped to ``.``) and its published source selection."""
    admitted = published_admission(root)
    if admitted is None:
        return None
    roots = sorted(old for old, rel in (admitted["index"].get("directory_aliases") or {}).items()
                   if rel == "." and isinstance(old, str) and old.startswith("/") and Path(old) != root)
    return {"roots": roots, "source_manifest": _json(admitted["source_path"]),
            "source_manifest_sha256": admitted["source_manifest_sha256"]}


def project_rows(manifest: dict, project: str) -> list[dict]:
    """Resolve a project's selection against the manifest's single row table."""
    projects = manifest.get("project_manifests")
    if projects is not None:
        if project not in projects:
            raise ManifestError("project is absent from history selection: " + project)
        local = projects[project]
    else:
        if manifest.get("project") != project:
            raise ManifestError("project is absent from history selection: " + project)
        local = manifest
    if "selected_row_indices" not in local:
        return local["selected_rows"]
    rows, indices = manifest["selected_rows"], local["selected_row_indices"]
    if (not isinstance(indices, list) or any(type(i) is not int or i < 0 or i >= len(rows)
                                            for i in indices)
            or indices != sorted(set(indices))):
        raise ManifestError("invalid project history row selection: " + project)
    return [rows[i] for i in indices]



def _lineage_error(reason):
    raise ManifestError('retained history lineage refused: ' + reason)


def _canonical_digest(value):
    from laplace.core.identity import canonical_digest
    return canonical_digest(value)


def _import_rows(project, sessions, digest, stamp=None):
    result = []
    for session in sessions:
        row = {'record': 'writing-session-import', 'id': 'IMPORT-' + hashlib.sha256((digest + session).encode()).hexdigest()[:24],
               'session_id': session, 'project': project, 'source_manifest_sha256': digest}
        if stamp is not None:
            row['ts'] = stamp
        result.append(row)
    return result


def _prior_history(root, project, read_rows):
    try:
        return _read_prior_history(root, project, read_rows)
    except (KeyError, TypeError, AttributeError) as exc:
        _lineage_error('malformed prior selection: ' + type(exc).__name__)


def _read_prior_history(root, project, read_rows):
    """Admit local immutable selection metadata, never the source root's filesystem."""
    handover = _safe(root, 'project-handover.json')
    if handover.exists():
        receipt = _json(handover)
        if not isinstance(receipt, dict) or receipt.get('schema') != 'laplace.project-data-handover/1':
            _lineage_error('unknown handover receipt')
        plan = receipt.get('plan')
        if not isinstance(plan, dict) or plan.get('schema') != 'laplace.project-data-plan/1' or _canonical_digest({k: v for k, v in plan.items() if k != 'manifest_digest'}) != plan.get('manifest_digest'):
            _lineage_error('handover canonical selection digest changed')
        if plan.get('project') != project:
            return None
        if plan.get('registry_row', {}).get('name') != project:
            _lineage_error('project/registry namespace disagreement')
        if not isinstance(plan.get('sessions'), list) or any(not isinstance(s, str) for s in plan['sessions']):
            _lineage_error('invalid retained session selection')
        return {'rows': plan.get('rows'), 'all_rows': plan.get('rows'), 'source_root': plan.get('source_root'),
                'sessions': plan.get('sessions'), 'imports': _import_rows(project, plan.get('sessions', []), plan['manifest_digest']),
                'associations': plan.get('history_lineage', []), 'roots': ()}
    # Reuse the already shipped portability admission, factored here from its script.
    # Only index/report/source-manifest pins are checked, not mutable project files.
    admitted = published_admission(root)
    if admitted is None:
        if any(r[3].get('record') == 'writing-session-import' and _belongs(r[3], project) for r in read_rows(root, 'contract/talk.jsonl')):
            _lineage_error('imported history claims missing prior selection metadata')
        return None
    manifest = _json(admitted['source_path'])
    if project not in (manifest.get('projects') or [manifest.get('project')]):
        return None
    local = manifest.get('project_manifests', {}).get(project, manifest)
    if local.get('registry_selection', {}).get('selected_row', {}).get('name') != project:
        _lineage_error('published project namespace disagreement')
    rows = project_rows(manifest, project)
    sessions = [r['id'] for r in rows if r.get('record') == 'writing-session']
    digest = _sha((json.dumps(local, indent=2, ensure_ascii=False, sort_keys=True) + '\n').encode())
    roots = tuple(old for old, rel in admitted['index'].get('directory_aliases', {}).items() if rel == '.' and isinstance(old, str) and old.startswith('/'))
    return {'rows': rows, 'all_rows': manifest.get('selected_rows'), 'source_root': manifest.get('repo_root'),
            'sessions': sessions, 'imports': _import_rows(project, sessions, digest, admitted['report'].get('created')),
            'associations': local.get('history_lineage', []), 'roots': roots}


def _owned_history_pairs(project, rows):
    """Project qualification for local ledger coordinates, independent of host roots."""
    sessions = {r[3].get('id') for r in rows if r[0] == 'contract/talk.jsonl' and r[3].get('record') == 'writing-session' and _belongs(r[3], project)}
    turns = {r[3].get('id') for r in rows if r[0] == 'contract/talk.jsonl' and r[3].get('record') == 'writing-turn' and _belongs(r[3], project)}
    pairs = set()
    for file, _, _, row in rows:
        if file == 'contract/journal.jsonl':
            continue
        scoped = _belongs(row, project)
        if file == 'contract/talk.jsonl' and not row.get('project', row.get('corpus')):
            scoped = row.get('session_id') in sessions or row.get('turn_id') in turns
        if file == 'contract/dispatches.jsonl':
            scoped = row.get('record') == 'workflow-definition' and row.get('scope') == {'kind': 'project', 'namespace': project}
        if file == 'corpus_friction/' + project + '.jsonl':
            scoped = row.get('project', row.get('corpus', project)) == project
        if not scoped:
            _lineage_error('retained row is not owned by the selected project')
        if row.get('id'):
            pairs.add((file, row['id']))
    return pairs


def _bank_associations(root, project, rows, inherited=None, recorded_roots=()):
    pairs = _owned_history_pairs(project, rows)
    inherited = inherited or {}
    associations = {}
    for file, _, raw, row in rows:
        if file != 'contract/journal.jsonl' or row.get('record') != 'bank':
            continue
        digest = _sha(raw)
        old = inherited.get(digest)
        if old is not None:
            if (set(old) != {'row_sha256', 'project', 'store', 'source_store', 'row_id'} or not all(isinstance(v, str) for v in old.values()) or old['project'] != project
                    or old['source_store'] != row.get('store') or old['row_id'] != row.get('row_id')
                    or (old['store'], old['row_id']) not in pairs):
                _lineage_error('bank store association is not exact/project-qualified')
            association = old
        else:
            store = _journal_store_key(root, row.get('store'), recorded_roots)
            if (store, row.get('row_id')) not in pairs:
                _lineage_error('selected bank has no verified local owner-store association')
            association = {'row_sha256': digest, 'project': project, 'store': store,
                           'source_store': row['store'], 'row_id': row['row_id']}
        associations[digest] = association
    return associations


def retained_history(root, project, *, read_rows=None):
    """Verify exact retained rows/order locally, allowing later ordinary appends/edits.

    Source paths are lexical evidence only. Only the fixed local ledger coordinates
    are ever read. No mutable output-file hash is a prerequisite for this proof.
    """
    read_rows = read_rows or _rows
    prior = _prior_history(root, project, read_rows)
    if prior is None:
        return [], {}
    allowed = {'contract/talk.jsonl', 'contract/journal.jsonl', 'contract/dispatches.jsonl',
               'corpus_friction/work_orders.jsonl', 'corpus_friction/' + project + '.jsonl'}
    own, all_rows = prior['rows'], prior['all_rows']
    if not isinstance(own, list) or not isinstance(all_rows, list) or len(all_rows) > 100_000:
        _lineage_error('invalid or oversized prior row selection')
    for rows in (own, all_rows):
        if any(not isinstance(r, dict) or not isinstance(r.get('file'), str) or type(r.get('line')) is not int or r['line'] < 1 for r in rows):
            _lineage_error('invalid prior row coordinate')
        coordinates = [(r['file'], r['line']) for r in rows]
        if coordinates != sorted(set(coordinates)):
            _lineage_error('prior row selection order/coordinates changed')
    positions = {(r['file'], r['line']): i for i, r in enumerate(all_rows)}
    if any(r['file'] not in allowed or positions.get((r['file'], r['line'])) is None or all_rows[positions[(r['file'], r['line'])]] != r for r in own):
        _lineage_error('prior project selection is not an exact subset')
    local, retained = {}, []
    for file in {r['file'] for r in own} | {'contract/talk.jsonl'}:
        # The original output concatenated global selected rows in their original
        # order; foreign selected rows may interleave in a legacy multi-project export.
        local[file] = read_rows(root, file)
        global_file = [r for r in all_rows if r['file'] == file]
        selected = {(r['file'], r['line']) for r in own}
        for ordinal, expected in enumerate(global_file):
            if (file, expected['line']) not in selected:
                continue
            if ordinal >= len(local[file]):
                _lineage_error('retained history row is missing: ' + file)
            actual = local[file][ordinal]
            observed = _row_record(actual)
            if {k: v for k, v in observed.items() if k != 'line'} != {k: v for k, v in expected.items() if k != 'line'}:
                _lineage_error('retained history bytes/order changed: ' + file)
            retained.append(actual)
    sessions = sorted(r[3]['id'] for r in retained if r[0] == 'contract/talk.jsonl' and r[3].get('record') == 'writing-session')
    if sorted(prior['sessions']) != sessions:
        _lineage_error('retained session namespace/selection changed')
    cut = sum(r['file'] == 'contract/talk.jsonl' for r in all_rows)
    for expected in prior['imports']:
        matches = [r for r in local['contract/talk.jsonl'][cut:] if r[3].get('id') == expected['id']]
        if len(matches) != 1 or matches[0][3] != expected:
            _lineage_error('import boundary does not bind the prior canonical selection')
    supplied = prior['associations']
    if not isinstance(supplied, list) or any(not isinstance(a, dict) or not isinstance(a.get('row_sha256'), str) for a in supplied):
        _lineage_error('invalid inherited bank association')
    inherited = {a['row_sha256']: a for a in supplied}
    banks = {_sha(r[2]) for r in retained if r[0] == 'contract/journal.jsonl' and r[3].get('record') == 'bank'}
    if len(inherited) != len(supplied) or not set(inherited) <= banks:
        _lineage_error('bank association names no exact retained row')
    source = prior['source_root']
    if not isinstance(source, str) or not Path(source).is_absolute() or '..' in Path(source).parts:
        _lineage_error('invalid recorded source root')
    associations = _bank_associations(Path(source), project, retained, inherited, prior['roots'])
    acts = {r[3].get('act_id') for r in retained if r[3].get('record') == 'bank'}
    if any(r[0] == 'contract/journal.jsonl' and r[3].get('record') not in {'bank', 'act', 'act_end'} for r in retained):
        _lineage_error('unknown retained journal owner')
    if any(r[0] == 'contract/journal.jsonl' and r[3].get('record') in {'act', 'act_end'} and r[3].get('act_id') not in acts for r in retained):
        _lineage_error('retained act is not attributable')
    return retained, associations


def selected_file_coordinate(root, project, path, scope='project'):
    """One explicitly selected local file, under the existing home/private fence.

    A read coordinate is not export permission. Packaging separately requires
    explicit permitted inclusion; no external root or private omission metadata.
    """
    from laplace.pipeline import registry
    from laplace.manuscript import manuscript_source
    root=Path(root).resolve();item=registry.resolve(project,repo_root=root)
    if item is None or scope not in {'project','manuscript'}:raise ManifestError('Selected file owner is unavailable.')
    if not isinstance(path,str) or not path or Path(path).is_absolute() or '..' in Path(path).parts:
        raise ManifestError('Selected file coordinate is not local.')
    if scope=='project':
        base=item.path(item.project_dir,root) if item.project_dir else None
    else:
        source=manuscript_source.resolve(project,repo_root=root)
        base=root/source['manuscript_dir'] if source.get('manuscript_dir') and not source.get('foreign') else None
    if base is None or not base.resolve().is_relative_to(root):raise ManifestError('Selected file home is unavailable.')
    relative=(base/Path(path)).relative_to(root)
    if _excluded(relative) or {'.laplace-state','.laplace-cache','.auth','.credentials'} & set(relative.parts):
        raise ManifestError('Selected content is excluded by its custody owner.')
    target=_safe(root,relative.as_posix())
    if not target.is_file():raise ManifestError('Selected file bytes are unavailable.')
    return target,relative.as_posix()


def selected_file(root, project, path, scope='project'):
    target,relative=selected_file_coordinate(root,project,path,scope)
    return target,relative,_file_record(Path(root).resolve(),target)
