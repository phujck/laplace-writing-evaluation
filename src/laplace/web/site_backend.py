def _gates_verdict_line(result: dict) -> str:
    """The machine-parsable sentinel (the pipe-swallow fix): the true LAST
    line of ``gates`` output, so a truncated read (``tail -1``, the last
    line of a log) still carries the whole verdict even if ``gates | tail``
    or similar drops everything above it. ``VERDICT=PASS`` or
    ``VERDICT=FAIL checks=<n_failed>/<n_total> reasons=<comma-joined names>``,
    where the reasons are the failing gates' own names."""
    gates = result["gates"]
    failed = [g["name"] for g in gates if not g["ok"]]
    if not failed:
        return "VERDICT=PASS"
    return f"VERDICT=FAIL checks={len(failed)}/{len(gates)} reasons={','.join(failed)}"


def _main(argv: list[str]) -> int:
    cmd = argv[0] if argv else ""
    if cmd == "render":
        result = render_site()
        print(f"rendered: {len(result['written'])} written, "
              f"{len(result['unchanged'])} unchanged, "
              f"{len(result['errors'])} errors")
        for w in result["written"]:
            print(f"  written   {w}")
        for e in result["errors"]:
            print(f"  ERROR     {e['path']}: {e['error']}")
        return 1 if result["errors"] else 0
    if cmd == "check":
        result = check_site()
        if result["ok"]:
            print("check_site: clean (every page == render(spine, content))")
            return 0
        print(f"check_site: DRIFT -- {len(result['drift'])} page(s), "
              f"{len(result['errors'])} error(s)")
        for d in result["drift"]:
            print(f"  drift  {d['path']}: {d['reason']}")
        for e in result["errors"]:
            print(f"  error  {e['path']}: {e['error']}")
        return 1
    if cmd == "gates":
        skip_visual = "--skip-visual" in argv[1:]
        result = run_gates(skip_visual=skip_visual)
        print("=" * 70)
        print("site gates -- the one pre-push ritual")
        print("=" * 70)
        for g in result["gates"]:
            status = "SKIP" if g["skipped"] else ("PASS" if g["ok"] else "FAIL")
            print(f"[{status}] {g['name']}")
            for line in g["detail"]:
                print(f"    {line}")
        print("-" * 70)
        print("VERDICT: " + ("GREEN -- clear to push" if result["ok"] else "RED -- fix before push"))
        print(_gates_verdict_line(result))  # LAST LINE: machine-parsable, survives a truncated read
        return 0 if result["ok"] else 1
    print(__doc__)
    print("usage: python -m laplace.web.site_backend render|check|gates [--skip-visual]")
    return 2


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(_main(sys.argv[1:]))
