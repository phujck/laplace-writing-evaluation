def render_head(site: dict, page: dict) -> str:
    """The one head/meta family (drift d): full rel=me cluster, OG + Twitter
    generated from spine fields, google-site-verification in one place, the
    JetBrains-Mono-inclusive font URL (drift f), and the #0a0e1a theme colour
    (drift e). Per-page authored raw blocks (JSON-LD, inline <style>/preloads)
    are carried verbatim; the meta STRUCTURE is generated."""
    L: list[str] = []
    L.append('  <meta charset="UTF-8">')
    L.append('  <meta name="viewport" content="width=device-width, initial-scale=1">')
    L.append(f'  <meta name="theme-color" content="{site["theme_color"]}">')
    L.append("")
    L.append(f'  <title>{page["title"]}</title>')
    L.append(f'  <meta name="description" content="{page["description"]}">')
    L.append(f'  <meta name="author" content="{site["author"]}">')
    # Per-page robots directive (unlisted pages set "noindex, nofollow, noarchive").
    L.append(f'  <meta name="robots" content="{page.get("robots", "index, follow")}">')
    L.append(f'  <link rel="canonical" href="{page["canonical"]}">')
    L.append("")
    L.append("  <!-- Google Search Console -->")
    L.append(f'  <meta name="google-site-verification" content="{site["google_site_verification"]}">')
    L.append("")
    L.append("  <!-- Favicon & manifest -->")
    L.append('  <link rel="icon" href="/favicon.svg" type="image/svg+xml">')
    L.append('  <link rel="manifest" href="/manifest.json">')
    L.append("")
    L.append("  <!-- Identity consolidation -->")
    for url in site["rel_me"]:
        L.append(f'  <link rel="me" href="{url}">')
    L.append("")
    L.append("  <!-- Open Graph -->")
    L.append(f'  <meta property="og:type" content="{page["og_type"]}">')
    L.append(f'  <meta property="og:url" content="{page["canonical"]}">')
    L.append(f'  <meta property="og:title" content="{page["og_title"]}">')
    L.append(f'  <meta property="og:description" content="{page["og_description"]}">')
    L.append(f'  <meta property="og:image" content="{page["og_image"]}">')
    if page.get("og_image_width") and page.get("og_image_height"):
        L.append(f'  <meta property="og:image:width" content="{page["og_image_width"]}">')
        L.append(f'  <meta property="og:image:height" content="{page["og_image_height"]}">')
    L.append(f'  <meta property="og:site_name" content="{site["og_site_name"]}">')
    L.append(f'  <meta property="og:locale" content="{site["og_locale"]}">')
    if page["og_type"] == "profile":
        L.append('  <meta property="profile:first_name" content="Gerard">')
        L.append('  <meta property="profile:last_name" content="McCaul">')
    L.append("")
    L.append("  <!-- Twitter Card -->")
    L.append(f'  <meta name="twitter:card" content="{page["twitter_card"]}">')
    L.append(f'  <meta name="twitter:title" content="{page["twitter_title"]}">')
    L.append(f'  <meta name="twitter:description" content="{page["twitter_description"]}">')
    L.append(f'  <meta name="twitter:image" content="{page.get("twitter_image") or page["og_image"]}">')
    L.append("")
    # JSON-LD: per-page block if present, else the site-wide Person node (the
    # identity anchor extracted from index -- a site token). Preserved verbatim.
    jsonld = page.get("jsonld") or site.get("jsonld_person")
    if jsonld:
        L.append("  <!-- JSON-LD -->")
        L.append('  <script type="application/ld+json">')
        L.append(jsonld)
        L.append("  </script>")
        L.append("")
    # Per-page authored head extras (preloads on index; inline <style> blocks on
    # music/writing/visualisations). Carried verbatim -- authorship, not drift.
    if page.get("head_extra"):
        L.append(page["head_extra"])
        L.append("")
    # Fonts + stylesheet (site-wide) + any page-local stylesheet (talks.css).
    L.append('  <link rel="preconnect" href="https://fonts.googleapis.com">')
    L.append('  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>')
    L.append(f'  <link href="{site["font_url"]}" rel="stylesheet">')
    # Identity tokens (N55) projected from palette.json -- BEFORE style.css so the
    # stylesheet consumes the projected custom properties.
    if site.get("identity_tokens"):
        L.append(site["identity_tokens"])
    L.append('  <link rel="stylesheet" href="/assets/css/style.css">')
    for css in page.get("extra_css", []):
        L.append(f'  <link rel="stylesheet" href="{css}">')
    return "\n".join(L)


def render_head_bare(site: dict, page: dict) -> str:
    """Minimal head for the bare layout (404): the unified title (drift c),
    theme colour (drift e) and JetBrains-inclusive font URL (drift f), and no
    OG/canonical/JSON-LD (a 404 asserts no shareable identity)."""
    L: list[str] = []
    L.append('  <meta charset="UTF-8">')
    L.append('  <meta name="viewport" content="width=device-width, initial-scale=1">')
    L.append(f'  <meta name="theme-color" content="{site["theme_color"]}">')
    L.append(f'  <title>{page["title"]}</title>')
    L.append("")
    L.append('  <link rel="preconnect" href="https://fonts.googleapis.com">')
    L.append('  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>')
    L.append(f'  <link href="{site["font_url"]}" rel="stylesheet">')
    if site.get("identity_tokens"):
        L.append(site["identity_tokens"])
    L.append('  <link rel="stylesheet" href="/assets/css/style.css">')
    return "\n".join(L)


def render_nav(site: dict, page: dict) -> str:
    """Site-wide nav with the active page marked. Every page carries every nav
    item -- Visualisations included (drift a: kills the orphan)."""
    L: list[str] = []
    L.append('  <nav class="nav" role="navigation" aria-label="Main navigation">')
    L.append('    <div class="nav-inner">')
    L.append(f'      <a href="/" class="nav-brand">{site["brand_html"]}</a>')
    L.append(
        '      <button class="nav-toggle" aria-label="Toggle menu" '
        'aria-expanded="false" aria-controls="nav-links">'
    )
    L.append("        <span></span><span></span><span></span>")
    L.append("      </button>")
    L.append('      <ul class="nav-links" id="nav-links">')
    for item in site["nav"]:
        active = ' class="active"' if item["key"] == page.get("nav_active") else ""
        L.append(f'        <li><a href="{item["href"]}"{active}>{item["label"]}</a></li>')
    L.append("      </ul>")
    L.append("    </div>")
    L.append("  </nav>")
    return "\n".join(L)


def render_footer(site: dict) -> str:
    """Site-wide footer -- literal © (drift b), one canonical link set."""
    L: list[str] = []
    L.append('  <footer class="footer">')
    L.append('    <div class="container">')
    L.append('      <div class="footer-inner">')
    L.append(f'        <p class="footer-text">{site["footer_text"]}</p>')
    L.append('        <ul class="footer-links">')
    for link in site["footer_links"]:
        ext = "" if link["href"].startswith("mailto:") else ' target="_blank" rel="noopener"'
        L.append(f'          <li><a href="{link["href"]}"{ext}>{link["label"]}</a></li>')
    L.append("        </ul>")
    L.append("      </div>")
    L.append("    </div>")
    L.append("  </footer>")
    return "\n".join(L)


def render_page(site: dict, page: dict, innards: str) -> str:
    """Assemble one full page: marker + shell(head/nav/footer) around innards.

    Deterministic in ``site`` + ``page`` + ``innards``. The ``bare`` layout
    (404) drops nav/footer and emits a minimal head."""
    marker = MARKER_TEMPLATE.format(page=page["path"])
    if page.get("layout") == "bare":
        parts = [
            "<!DOCTYPE html>",
            marker,
            '<html lang="en">',
            "",
            "<head>",
            render_head_bare(site, page),
            "</head>",
            "",
            "<body>",
            "",
            innards,
            "",
            '  <script src="/assets/js/main.js"></script>',
            "</body>",
            "",
            "</html>",
            "",
        ]
        return "\n".join(parts)

    tail = [
        '  <button class="back-to-top" aria-label="Back to top">↑</button>',
        '  <script src="/assets/js/main.js"></script>',
    ]
    if page.get("body_scripts"):
        tail.append(page["body_scripts"])

    parts = [
        "<!DOCTYPE html>",
        marker,
        '<html lang="en">',
        "",
        "<head>",
        render_head(site, page),
        "</head>",
        "",
        "<body>",
        "",
        render_nav(site, page),
        "",
        innards,
        "",
        render_footer(site),
        "",
        "\n".join(tail),
        "</body>",
        "",
        "</html>",
        "",
    ]
    return "\n".join(parts)


def render_one(site: dict, page: dict, root: Path) -> str:
    """Full rendered bytes for one spine page (reads its innards from disk)."""
    innards = load_innards(root, page["path"])
    return render_page(site, page, innards)


