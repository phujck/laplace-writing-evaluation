"""The one producer of the public site's shell (bite B2, website milestone one).

The website (``phujck.github.io`` -> ``gmccaul.co.uk``) is a registered engine
project (``kind="site"``, ``external_root="../phujck.github.io"``; registry.py).
Its shell -- the ``<head>`` meta family, the ``<nav>``, the ``<footer>`` -- is a
*projection*: generated deterministically from a SPINE (``site/spine.json``) plus
one template family, wrapped around each page's authored *innards*
(``site/content/<page>.html``). The law (blueprint 2026-07-11 §4):

    generated shell, authored innards -- the template owns everything OUTSIDE the
    content block; hand-tuning inside the content is authorship, not drift.

``render_site`` writes every page = ``shell(spine) + innards``. ``check_site``
re-renders to memory and diffs against the live files: a hand-touched SHELL
fails (live != render(spine)); changed innards WITHOUT a re-render also fails
(the live page no longer equals ``render(spine, content)``). ``update.ps1``-style
regex mutation of the head becomes mechanically impossible.

Deterministic: same spine + content -> byte-identical output (render twice ->
identical bytes). Zero third-party deps -- stdlib string templates only, to match
the engine's tex_backend style.

Every generated page opens with a marker comment naming the two authoring
surfaces (``site/content/<page>.html`` + ``site/spine.json``) so a cold human
never edits the generated shell by hand.

CLI::

    python -m laplace.web.site_backend render     # write all pages
    python -m laplace.web.site_backend check       # drift gate (exit 1 on drift)
    python -m laplace.web.site_backend gates [--skip-visual]  # the pre-push ritual (bite B5):
                                                            # drift+links+survival+meta+deslop+visual
"""

