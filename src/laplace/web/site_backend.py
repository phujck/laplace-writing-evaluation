MARKER_TEMPLATE = (
    "<!-- generated by laplace site_backend; edit site/content/{page} + "
    "site/spine.json, never this shell -->"
)


def resolve_site_root(repo_root: Path | None = None,
                      site_root: Path | None = None) -> Path:
    """The sibling-clone directory (the website's external root).

    ``site_root`` overrides everything (used by tests with a miniature site).
    Otherwise resolve the registered ``website`` project's external root.
    """
    if site_root is not None:
        return Path(site_root)
    proj = registry.resolve("website")
    resolved = proj.path(".", repo_root)
    if resolved is None:  # pragma: no cover -- registry guarantees a path
        raise RuntimeError("website project has no resolvable external root")
    return resolved.resolve()


def spine_path(root: Path) -> Path:
    return root / "site" / "spine.json"


def content_path(root: Path, page: str) -> Path:
    return root / "site" / "content" / page


def load_spine(root: Path) -> dict:
    return json.loads(spine_path(root).read_text(encoding="utf-8"))


def load_innards(root: Path, page: str) -> str:
    """Read a page's authored innards, normalised to have no leading/trailing
    blank lines (the template owns the join whitespace)."""
    return content_path(root, page).read_text(encoding="utf-8").strip("\n")


# ---------------------------------------------------------------------------
# The unified identity (N55): the site's colour custom properties are PROJECTED
# from the one token source ``templates/identity/palette.json`` (engine-side),
# not hand-written in style.css. site_backend emits the screen-dark mode as a
# ``<style id="identity-tokens">`` block into every page head; style.css keeps
# consuming the same custom-property NAMES (it owns only the non-colour tokens).
# Because the block lives in the rendered HTML, ``check_site`` drift-gates it for
# free -- edit palette.json and forget to re-render, and the gate bites.
# ---------------------------------------------------------------------------


def palette_path(repo_root: Path | None = None) -> Path:
    """The one identity token source (engine-side; NOT under the site root)."""
    root = Path(repo_root) if repo_root is not None else registry._repo_root()
    return root / "templates" / "identity" / "palette.json"


def load_palette(repo_root: Path | None = None,
                 palette_file: Path | None = None) -> dict:
    p = Path(palette_file) if palette_file is not None else palette_path(repo_root)
    return json.loads(p.read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# The other two authoring surfaces the gate family (bite B5) reads: the
# survival contract (site/must_survive.json, the B3 fixture) and the deslop
# allowlist (site/deslop_allow.json, this bite's own fixture -- already
# B3-flagged author prose, his call pending, seeded so the lint is green today
# but still catches genuinely NEW slop).
# ---------------------------------------------------------------------------


def must_survive_path(root: Path) -> Path:
    return root / "site" / "must_survive.json"


def load_must_survive(root: Path) -> list[dict]:
    p = must_survive_path(root)
    if not p.exists():
        return []
    return json.loads(p.read_text(encoding="utf-8"))


def deslop_allow_path(root: Path) -> Path:
    return root / "site" / "deslop_allow.json"


def load_deslop_allow(root: Path) -> list[str]:
    """Exact already-flagged strings the deslop gate must not fail on. Entries
    are either bare strings or ``{"text": ..., "note": ...}`` objects (the
    richer form is what ships in the real allowlist; tests may seed bare
    strings)."""
    p = deslop_allow_path(root)
    if not p.exists():
        return []
    data = json.loads(p.read_text(encoding="utf-8"))
    return [e["text"] if isinstance(e, dict) else e for e in data]


def identity_tokens_style(palette: dict, mode: str = "screen-dark") -> str:
    """Project one palette mode into the ``<style id="identity-tokens">`` block.

    Deterministic in (palette, mode): the declarations are emitted in the
    canonical ``tokens`` order, so re-render is byte-identical and the drift
    gate is meaningful. A token declared in ``tokens`` but missing from the mode
    raises ``KeyError`` -- an incomplete mode fails loudly rather than shipping a
    page with unresolved custom properties."""
    values = palette["modes"][mode]
    decls = "".join(f"--{k}:{values[k]};" for k in palette["tokens"])
    return f'  <style id="identity-tokens">:root{{{decls}}}</style>'


