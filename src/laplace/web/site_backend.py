def render_site(repo_root: Path | None = None,
                site_root: Path | None = None) -> dict:
    """Render every spine page and write it to its live path.

    Returns ``{"written": [...], "unchanged": [...], "errors": [...]}``. A page
    whose freshly-rendered bytes already equal the live file is ``unchanged``
    (so a re-run is idempotent: 0 written)."""
    root = resolve_site_root(repo_root=repo_root, site_root=site_root)
    spine = load_spine(root)
    site = spine["site"]
    site["identity_tokens"] = identity_tokens_style(load_palette(repo_root))
    written, unchanged, errors = [], [], []
    for page in spine["pages"]:
        try:
            rendered = render_one(site, page, root)
        except Exception as exc:  # noqa: BLE001 -- report, don't abort the run
            errors.append({"path": page.get("path"), "error": str(exc)})
            continue
        live = root / page["path"]
        current = live.read_text(encoding="utf-8") if live.exists() else None
        if current == rendered:
            unchanged.append(page["path"])
        else:
            live.parent.mkdir(parents=True, exist_ok=True)
            live.write_text(rendered, encoding="utf-8")
            written.append(page["path"])
    return {"written": written, "unchanged": unchanged, "errors": errors}


def check_site(repo_root: Path | None = None,
               site_root: Path | None = None) -> dict:
    """Re-render every spine page to memory and diff against the live file.

    Returns ``{"ok": bool, "drift": [...], "errors": [...]}``. ``drift`` lists
    pages where the live bytes differ from ``render(spine, content)`` -- a
    hand-touched shell, or innards changed without a re-render, or a missing
    page. Never writes."""
    root = resolve_site_root(repo_root=repo_root, site_root=site_root)
    spine = load_spine(root)
    site = spine["site"]
    site["identity_tokens"] = identity_tokens_style(load_palette(repo_root))
    drift, errors = [], []
    for page in spine["pages"]:
        try:
            rendered = render_one(site, page, root)
        except Exception as exc:  # noqa: BLE001
            errors.append({"path": page.get("path"), "error": str(exc)})
            continue
        live = root / page["path"]
        if not live.exists():
            drift.append({"path": page["path"], "reason": "missing (never rendered)"})
            continue
        if live.read_text(encoding="utf-8") != rendered:
            drift.append({"path": page["path"], "reason": "live bytes != render(spine, content)"})
    return {"ok": not drift and not errors, "drift": drift, "errors": errors}


# ---------------------------------------------------------------------------
# The gate family (bite B5): the ONE pre-push ritual. Every gate returns the
# same shape -- {"name", "ok", "skipped", "detail": [str, ...]} -- so `gates`
# can run them in order and print one verdict block. A gate that legitimately
# has nothing to check sets ``skipped`` (never fails the run); everything else
# fails the run iff ``detail`` is non-empty.
# ---------------------------------------------------------------------------

_TITLE_RE = re.compile(r"<title>(.*?)</title>", re.S)
_CANONICAL_RE = re.compile(r'<link rel="canonical"')
_OGTITLE_RE = re.compile(r'<meta property="og:title"')
_THEME_COLOR_RE = re.compile(r'<meta name="theme-color" content="([^"]*)"')


def _render_all(repo_root: Path | None, root: Path) -> list[tuple[dict, str | None, str | None]]:
    """(page, rendered_or_None, error_or_None) for every spine page -- the one
    render pass ``gate_meta`` and ``gate_deslop`` both scan (spine-rendered
    pages only; essays/viz/talks are separately-authored, not spine-templated,
    and are out of scope for meta/deslop by construction)."""
    spine = load_spine(root)
    site = spine["site"]
    site["identity_tokens"] = identity_tokens_style(load_palette(repo_root))
    out: list[tuple[dict, str | None, str | None]] = []
    for page in spine["pages"]:
        try:
            out.append((page, render_one(site, page, root), None))
        except Exception as exc:  # noqa: BLE001 -- report, don't abort the gate
            out.append((page, None, str(exc)))
    return out


def gate_drift(repo_root: Path | None = None, site_root: Path | None = None) -> dict:
    """Gate 1: the existing drift gate (``check_site``) -- live bytes must
    equal ``render(spine, content)`` for every page."""
    result = check_site(repo_root=repo_root, site_root=site_root)
    detail = [f'{d["path"]}: {d["reason"]}' for d in result["drift"]]
    detail += [f'{e["path"]}: ERROR {e["error"]}' for e in result["errors"]]
    return {"name": "drift", "ok": result["ok"], "skipped": False, "detail": detail}


# --- links -------------------------------------------------------------

_HREF_SRC_RE = re.compile(r'(?:href|src)\s*=\s*(["\'])(.*?)\1', re.I)
_URI_SCHEME_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9+.\-]*://")


def _scoped_html_files(root: Path) -> list[Path]:
    """The LINKS-gate scope (B5 dispatch note): root pages + essays/ + viz/
    (recursive) + the two redirect stubs. Deliberately excludes demo/,
    memories/, review/, unlisted/, and the rest of talks/ (including
    talks/*/assets internals and the talk decks themselves) -- quarantined /
    untouchable trees and self-contained decks this gate does not reach into."""
    files = sorted(root.glob("*.html"))
    files += sorted(root.glob("essays/*.html"))
    files += sorted(root.glob("viz/**/*.html"))
    for stub in ("talks/laws-of-learning/index.html", "talks/laws-of-learning-v2/index.html"):
        p = root / stub
        if p.exists():
            files.append(p)
    return files


def _normalize_href(raw: str, file_rel_dir: str) -> str:
    """Resolve an href/src value to a site-root-relative absolute path
    (``/a/b.html``). Every internal link on the site is already absolute
    (``/...``); relative forms are resolved against the referring file's
    directory defensively, should one ever appear. Trailing-slash
    (directory-style) shape is preserved through the normalisation -- it is
    load-bearing for the dir-vs-file resolution in ``_resolve_on_disk``."""
    joined = raw if raw.startswith("/") else posixpath.join("/", file_rel_dir, raw)
    had_slash = joined.endswith("/") and joined != "/"
    normed = posixpath.normpath(joined)
    if had_slash and not normed.endswith("/"):
        normed += "/"
    return normed


def _classify_link(raw_url: str, base_url: str, file_rel_dir: str) -> str | None:
    """The normalized site-root-relative path to resolve on disk, or None if
    ``raw_url`` is out of the links gate's scope: empty, a fragment-only
    anchor (``#foo``, bare ``#``), ``mailto:``/``tel:``/``javascript:``/
    ``data:``, or any other URI scheme (external, incl. protocol-relative
    ``//...``). A same-origin absolute URL (``{base_url}/...``) is rewritten
    to a path and IS checked -- it is our own canonical/self-link, not really
    external."""
    url = raw_url.strip()
    if not url or url.startswith("#"):
        return None
    if url.startswith(("mailto:", "tel:", "javascript:", "data:")):
        return None
    if url.startswith(base_url):
        url = url[len(base_url):] or "/"
    elif url.startswith("//") or _URI_SCHEME_RE.match(url):
        return None
    url = url.split("#", 1)[0].split("?", 1)[0]
    if not url:
        return None
    return _normalize_href(url, file_rel_dir)


def _dir_index(path: str, root: Path) -> Path:
    rel = path.strip("/")
    return (root / rel / "index.html") if rel else (root / "index.html")


def _resolve_on_disk(path: str, root: Path) -> Path | None:
    """The concrete file ``path`` resolves to, honouring the site's URL
    shapes: ``/`` or ``/x/`` (a directory -- GitHub Pages serves its
    index.html), ``/x.html`` (a literal file), and defensively ``/x`` with no
    extension and no trailing slash (treated as the directory form). None if
    nothing on disk matches any shape."""
    if path == "/" or path.endswith("/"):
        cand = _dir_index(path, root)
        return cand if cand.exists() else None
    cand = root / path.lstrip("/")
    if cand.exists():
        return cand
    if "." not in cand.name:
        alt = cand / "index.html"
        return alt if alt.exists() else None
    return None


def _target_exists(path: str, root: Path) -> bool:
    return _resolve_on_disk(path, root) is not None


def _must_survive_redirect_targets(root: Path) -> set[str]:
    return {e["url"] for e in load_must_survive(root) if e.get("kind") == "redirect"}


def gate_links(repo_root: Path | None = None, site_root: Path | None = None) -> dict:
    """Gate 2: every internal href/src across the LINKS scope resolves --
    exists on disk (``/x.html`` and ``/x/`` normalised, anchors/mailto/external
    ignored) OR is a declared ``kind=redirect`` entry in must_survive.json."""
    root = resolve_site_root(repo_root=repo_root, site_root=site_root)
    base_url = load_spine(root)["site"]["base_url"]
    redirect_targets = _must_survive_redirect_targets(root)

    detail = []
    for f in _scoped_html_files(root):
        text = f.read_text(encoding="utf-8")
        rel_dir = f.parent.relative_to(root).as_posix()
        if rel_dir == ".":
            rel_dir = ""
        for m in _HREF_SRC_RE.finditer(text):
            raw = m.group(2)
            target = _classify_link(raw, base_url, rel_dir)
            if target is None:
                continue
            if _target_exists(target, root) or target in redirect_targets:
                continue
            line = text.count("\n", 0, m.start()) + 1
            detail.append(f"{f.relative_to(root).as_posix()}:{line}: "
                          f"broken link '{raw}' (resolved '{target}')")

    return {"name": "links", "ok": not detail, "skipped": False, "detail": detail}


# --- survival ------------------------------------------------------------

_REFRESH_RE = re.compile(r'http-equiv="refresh"\s+content="[^"]*url=([^"]+)"', re.I)


def gate_survival(repo_root: Path | None = None, site_root: Path | None = None) -> dict:
    """Gate 3: every ``site/must_survive.json`` entry (the B3 fixture) --
    page/asset/special must exist on disk; redirect must have its stub file
    AND a meta-refresh whose target exists. Missing = a named failure."""
    root = resolve_site_root(repo_root=repo_root, site_root=site_root)
    base_url = load_spine(root)["site"]["base_url"]

    detail = []
    for entry in load_must_survive(root):
        url, kind = entry["url"], entry["kind"]
        if kind in ("page", "asset", "special"):
            if not _target_exists(url, root):
                detail.append(f"{url} ({kind}): missing on disk")
        elif kind == "redirect":
            stub = _resolve_on_disk(url, root)
            if stub is None:
                detail.append(f"{url} (redirect): stub file missing")
                continue
            text = stub.read_text(encoding="utf-8")
            m = _REFRESH_RE.search(text)
            if not m:
                detail.append(f"{url} (redirect): no meta-refresh in "
                              f"{stub.relative_to(root)}")
                continue
            target = m.group(1).strip()
            if target.startswith(base_url):
                target = target[len(base_url):] or "/"
            if not _target_exists(target, root):
                detail.append(f"{url} (redirect): meta-refresh target '{target}' missing")
        else:
            detail.append(f"{url}: unknown must_survive kind '{kind}'")

    return {"name": "survival", "ok": not detail, "skipped": False, "detail": detail}


# --- meta ------------------------------------------------------------------


def gate_meta(repo_root: Path | None = None, site_root: Path | None = None) -> dict:
    """Gate 4: over the spine-rendered full pages -- titles unique across
    pages; exactly one canonical link + an og:title on every full-layout page
    (404's bare layout has neither, by design -- ``render_head_bare``); the
    theme-color meta content equals the one token source (palette.json's
    screen-dark bg-primary), catching spine.json/palette.json drifting apart."""
    root = resolve_site_root(repo_root=repo_root, site_root=site_root)
    expected_theme = load_palette(repo_root)["modes"]["screen-dark"]["bg-primary"]

    detail: list[str] = []
    titles: dict[str | None, list[str]] = {}
    for page, rendered, error in _render_all(repo_root, root):
        path = page.get("path", "?")
        if error is not None:
            detail.append(f"{path}: ERROR rendering ({error})")
            continue
        title_m = _TITLE_RE.search(rendered)
        titles.setdefault(title_m.group(1).strip() if title_m else None, []).append(path)

        theme_m = _THEME_COLOR_RE.search(rendered)
        if theme_m is None:
            detail.append(f"{path}: no theme-color meta tag")
        elif theme_m.group(1) != expected_theme:
            detail.append(f"{path}: theme-color {theme_m.group(1)!r} != palette "
                          f"screen-dark bg-primary {expected_theme!r}")

        if page.get("layout") == "bare":
            continue  # 404: no canonical/OG by design
        n_canonical = len(_CANONICAL_RE.findall(rendered))
        if n_canonical != 1:
            detail.append(f"{path}: {n_canonical} <link rel=canonical> tag(s) (want exactly 1)")
        if not _OGTITLE_RE.search(rendered):
            detail.append(f"{path}: missing og:title")

    for title, paths in titles.items():
        if title is None:
            detail.append(f"no <title> found on: {paths}")
        elif len(paths) > 1:
            detail.append(f"duplicate title {title!r} across: {paths}")

    return {"name": "meta", "ok": not detail, "skipped": False, "detail": detail}


# --- deslop ------------------------------------------------------------------


class _VisibleTextExtractor(HTMLParser):
    """Strips ``<script>``/``<style>`` (and their content) and every tag,
    keeping the source line number of each remaining text chunk. Comments
    (including the generated-shell marker) are dropped by HTMLParser by
    default -- neither markup nor code nor the marker is authored prose."""

    _SUPPRESS_TAGS = {"script", "style"}

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.chunks: list[tuple[int, str]] = []
        self._suppress_depth = 0

    def handle_starttag(self, tag: str, attrs) -> None:  # noqa: ANN001
        if tag in self._SUPPRESS_TAGS:
            self._suppress_depth += 1

    def handle_endtag(self, tag: str) -> None:
        if tag in self._SUPPRESS_TAGS and self._suppress_depth:
            self._suppress_depth -= 1

    def handle_data(self, data: str) -> None:
        if self._suppress_depth or not data.strip():
            return
        self.chunks.append((self.getpos()[0], data))


def _visible_text_chunks(rendered_html: str) -> list[tuple[int, str]]:
    parser = _VisibleTextExtractor()
    parser.feed(rendered_html)
    parser.close()
    return parser.chunks


_SLOP_WORDS = (
    "honestly", "honest",
    "rigorously", "rigorous",
    "principled",
    "seamlessly", "seamless",
    "cutting-edge",
    "world-class",
    "state-of-the-art",
    "effortlessly", "effortless",
    "delve",
)
_SLOP_WORDS_RE = re.compile(r"\b(" + "|".join(_SLOP_WORDS) + r")\b", re.IGNORECASE)

_EPIGRAM_RE = re.compile(r"^(.+), not (.+)$")
_EPIGRAM_MAX_LEN = 60


def gate_deslop(repo_root: Path | None = None, site_root: Path | None = None) -> dict:
    """Gate 5: the tell-list lint (his live law, banked 2026-07-11, DESIGN
    2026-07-11 eigenengine-page-and-the-anti-generative-grammar.md sec.5) over
    VISIBLE TEXT of the spine-rendered pages: (a) virtue adjectives from a
    seeded list, anywhere; (b) the balanced '<A>, not <B>' epigram shape in
    short (<=60 char) standalone lines -- heading/tagline position only, body
    prose is exempt by construction (a paragraph is one long text chunk).
    Findings already covered by ``site/deslop_allow.json`` (B3-flagged author
    prose, his call pending) do not fail the gate."""
    root = resolve_site_root(repo_root=repo_root, site_root=site_root)
    allow = load_deslop_allow(root)

    detail = []
    for page, rendered, error in _render_all(repo_root, root):
        if error is not None:
            continue  # already reported by gate_meta
        path = page.get("path", "?")
        for lineno, raw_text in _visible_text_chunks(rendered):
            norm = " ".join(raw_text.split())
            if not norm:
                continue
            allowed = any(a in norm for a in allow)
            if allowed:
                continue

            for m in _SLOP_WORDS_RE.finditer(norm):
                detail.append(f"{path}:{lineno}: slop word {m.group(0)!r} in {norm[:90]!r}")

            if len(norm) <= _EPIGRAM_MAX_LEN and _EPIGRAM_RE.match(norm):
                detail.append(f"{path}:{lineno}: balanced-epigram shape {norm!r}")

    return {"name": "deslop", "ok": not detail, "skipped": False, "detail": detail}


# --- visual/mobile -----------------------------------------------------------

_MOBILE_WIDTH = 375


def _chrome_executable() -> str | None:
    """The chromium binary playwright drives, without triggering its own
    browser download -- the container ships one under
    ``$PLAYWRIGHT_BROWSERS_PATH`` (or ``/opt/pw-browsers``), same convention
    as the suite's browser tiers — whose own resolution now lives in
    ``tests/browser_fence.py`` (env → search → honest None, over both the
    chrome-linux and chrome-linux64 layouts), the shape this should grow into."""
    search_root = Path(os.environ.get("PLAYWRIGHT_BROWSERS_PATH", "/opt/pw-browsers"))
    candidates = sorted(search_root.glob("chromium-*/chrome-linux/chrome"))
    if candidates:
        return str(candidates[0])
    direct = search_root / "chromium"
    return str(direct) if direct.exists() else None


def gate_visual(repo_root: Path | None = None, site_root: Path | None = None,
                skip: bool = False) -> dict:
    """Gate 6: the mobile law made mechanical -- at a 375px viewport, every
    root page must have ``document.scrollingElement.scrollWidth <=
    window.innerWidth`` (no horizontal overflow). Serves the site root over
    loopback HTTP (stdlib ``http.server``, the in-process equivalent of
    ``python3 -m http.server`` -- no subprocess lifecycle to manage) and drives
    real Chromium via Playwright. Gracefully SKIPPED (never fails the run)
    when ``--skip-visual`` is passed, Playwright is not installed, or no
    Chromium build is found -- but always with a LOUD note, never silent."""
    if skip:
        return {"name": "visual", "ok": True, "skipped": True,
                "detail": ["--skip-visual: mobile-width gate NOT RUN"]}
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return {"name": "visual", "ok": True, "skipped": True,
                "detail": ["LOUD: playwright not installed -- "
                           "mobile-width gate SKIPPED, NOT VERIFIED"]}
    chrome = _chrome_executable()
    if chrome is None:
        return {"name": "visual", "ok": True, "skipped": True,
                "detail": ["LOUD: no Chromium build found ($PLAYWRIGHT_BROWSERS_PATH / "
                           "/opt/pw-browsers) -- mobile-width gate SKIPPED, NOT VERIFIED"]}

    root = resolve_site_root(repo_root=repo_root, site_root=site_root)
    pages = [p["path"] for p in load_spine(root)["pages"]]

    handler = functools.partial(SimpleHTTPRequestHandler, directory=str(root))
    httpd = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    thread = threading.Thread(target=httpd.serve_forever, daemon=True)
    thread.start()
    port = httpd.server_address[1]

    detail: list[str] = []
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(executable_path=chrome)
            try:
                page = browser.new_page(viewport={"width": _MOBILE_WIDTH, "height": 800})
                page.set_default_timeout(15000)
                for path in pages:
                    try:
                        # 'domcontentloaded', not 'load': render-blocking local CSS
                        # (in <head>) is already applied by then, and the layout check
                        # must not hang/flake on cross-origin font/API fetches that a
                        # sandboxed or offline pre-push run may never complete.
                        page.goto(f"http://127.0.0.1:{port}/{path}", wait_until="domcontentloaded")
                        scroll_w, inner_w = page.evaluate(
                            "() => [document.scrollingElement.scrollWidth, window.innerWidth]")
                    except Exception as exc:  # noqa: BLE001 -- report, don't abort the gate
                        detail.append(f"{path}: ERROR loading at 375px ({exc})")
                        continue
                    if scroll_w > inner_w:
                        detail.append(f"{path}: horizontal overflow at 375px "
                                      f"(scrollWidth={scroll_w} > innerWidth={inner_w})")
            finally:
                browser.close()
    finally:
        httpd.shutdown()
        thread.join(timeout=5)

    return {"name": "visual", "ok": not detail, "skipped": False, "detail": detail}


def run_gates(repo_root: Path | None = None, site_root: Path | None = None,
             skip_visual: bool = False) -> dict:
    """The one pre-push ritual (bite B5): drift, links, survival, meta,
    deslop, visual/mobile -- in order, one verdict. Returns
    ``{"ok": bool, "gates": [{"name","ok","skipped","detail"}, ...]}``."""
    gates = [
        gate_drift(repo_root=repo_root, site_root=site_root),
        gate_links(repo_root=repo_root, site_root=site_root),
        gate_survival(repo_root=repo_root, site_root=site_root),
        gate_meta(repo_root=repo_root, site_root=site_root),
        gate_deslop(repo_root=repo_root, site_root=site_root),
        gate_visual(repo_root=repo_root, site_root=site_root, skip=skip_visual),
    ]
    return {"ok": all(g["ok"] for g in gates), "gates": gates}


