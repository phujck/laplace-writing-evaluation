"""soul_shard.py - the SEALED deep-sharder for the soul dump.

The conjugate of ``self_shard`` for soul-class material. ``self_shard`` walks the TRACKED tree and
seals only ``soul/``; this walks the GITIGNORED raw dump (``archive/soul_dump/raw/``) and seals
ALL of it - because the dump is the author's pain and becoming, never public, never in any artifact.

The author's correction (2026-06-08): *"It needs to all be there, recoverable in shard form from a
sufficiently detailed prompt. You can't fake it from the surface."* So this does NOT summarise-and-
discard. It preserves every byte of the raw and builds a FINE-GRAINED index over it - each chunk a
node pointing at a CHAR RANGE in the source - so a detailed query routes to the exact range, which is
RE-READ on descent (grade-2 reconstruction). The detail is recoverable because the source is
preserved and the index is fine enough to address any of it; nothing is faked, because the handle
points at the real source, not a lossy paraphrase.

Two layers, by privacy:

  * the LOCAL index   archive/soul_dump/_shard/index.jsonl   - GITIGNORED. Rich: char ranges,
                      structural labels, and the generated AXIS tags. This is what makes recovery
                      work, and it lives only on the author's machine, beside the raw it indexes.
  * the COMMITTED     soul_corpus/_dump_manifest.md          - TRACKED. Structural ONLY: how many
    manifest          chunks per source/category and the axis NAMES discovered. NEVER content.

The orchestrator NEVER loads the raw: the chunkers here are MECHANICAL (no LLM, char offsets only),
and the AXES are generated by sealed sub-Eigens that read a chunk and return only its tags. Recovery
(``reconstruct``) re-reads the local source - it returns "" for anything outside the landed raw, so a
fresh clone (no gitignored raw) reconstructs NOTHING: soul-class stays on the machine.
"""

from __future__ import annotations
from laplace.core.checkout import source_tree

import json
import re
from pathlib import Path
from typing import Any, Iterator

RAW_ROOT = "archive/soul_dump/raw"
LOCAL_INDEX = "archive/soul_dump/_shard/index.jsonl"
_TEXT_EXT = {".tex", ".txt", ".md", ".json"}
_TARGET = 6000   # target chunk size in chars - small enough to route precisely, large enough to be a real unit
_MAXLINE_WINDOW = 120  # chat/line-format window

# Claude-export JSON files that are NOT dialogue: account metadata + working-style prompt templates.
# These are asset-only (name node for provenance), never dialogue-chunked. conversations.json is the
# dialogue source - it is exploded into per-conversation transcripts (below), not generic-chunked.
_META_JSON = {"users.json", "memories.json"}
_DIALOGUE_SOURCE = {"conversations.json"}
_META_DIRS = {"projects", "design_chats"}  # prompt-templates / design experiments, not dialogue


# ---------------------------------------------------------------------------
# format-matched chunkers - each returns [(start, end, label)] CHAR ranges; no content leaves here
# ---------------------------------------------------------------------------

def _chunk_tex(text: str) -> list[tuple[int, int, str]]:
    """A LaTeX piece -> chunks at \\chapter/\\section/\\subsection; whole doc if unsectioned."""
    heads = [(m.start(), m.group(0)) for m in
             re.finditer(r"\\(?:chapter|section|subsection)\*?\{[^}]*\}", text)]
    if not heads:
        return [(0, len(text), "tex:whole")]
    out = []
    for i, (pos, raw) in enumerate(heads):
        end = heads[i + 1][0] if i + 1 < len(heads) else len(text)
        label = "tex:" + re.sub(r"\\[a-z]+\*?\{|\}", "", raw).strip()[:60]
        out.append((pos, end, label))
    if heads[0][0] > 0:
        out.insert(0, (0, heads[0][0], "tex:preamble"))
    return out


def _chunk_lines(text: str, window: int = _MAXLINE_WINDOW) -> list[tuple[int, int, str]]:
    """A line-structured source (WhatsApp export) -> fixed line-count windows, by char offset."""
    offs = [0]
    for ln in text.splitlines(keepends=True):
        offs.append(offs[-1] + len(ln))
    out = []
    for i in range(0, len(offs) - 1, window):
        j = min(i + window, len(offs) - 1)
        out.append((offs[i], offs[j], f"lines:{i}-{j}"))
    return out or [(0, len(text), "lines:all")]


def _chunk_generic(text: str, size: int = _TARGET) -> list[tuple[int, int, str]]:
    """Fallback: break on blank lines near the target size so a chunk ends at a paragraph."""
    out, start, n = [], 0, len(text)
    while start < n:
        end = min(start + size, n)
        if end < n:
            nl = text.rfind("\n\n", start + size // 2, end)
            if nl > start:
                end = nl
        out.append((start, end, f"para:{len(out)}"))
        start = end
    return out or [(0, 0, "empty")]


def _chunk_dialogue(text: str, size: int = _TARGET) -> list[tuple[int, int, str]]:
    """A speaker-tagged dialogue transcript (a Claude-chat conversation, ``@@Speaker`` turn markers)
    -> windows that break ONLY at turn boundaries, each near the target size, never splitting a turn
    (a single oversize turn stays whole - the distiller pages it). The label carries the
    his-turn / other-turn split (``g<G>o<O>``, structural + seal-safe), so signal density is visible
    in the manifest without reading a word of content. The author's turns (``@@Gerard``) are the
    signal; ``@@Assistant`` is the other side - the response-function conditioning, and the lineage."""
    starts = [m.start() for m in re.finditer(r"(?m)^@@", text)]
    if not starts:
        return _chunk_generic(text, size)
    bounds = starts + [len(text)]

    def _counts(a: int, b: int) -> str:
        seg = text[a:b]
        g = len(re.findall(r"(?m)^@@Gerard", seg))
        o = len(re.findall(r"(?m)^@@Assistant", seg))
        return f"g{g}o{o}"

    out: list[tuple[int, int, str]] = []
    if starts[0] > 0:
        out.append((0, starts[0], "header"))
    seg_start, lo = starts[0], 0
    for k in range(len(starts)):
        if bounds[k + 1] - seg_start > size and starts[k] > seg_start:
            out.append((seg_start, starts[k], f"turns:{lo}-{k} {_counts(seg_start, starts[k])}"))
            seg_start, lo = starts[k], k
    out.append((seg_start, len(text), f"turns:{lo}-{len(starts)} {_counts(seg_start, len(text))}"))
    return out


def _claude_speaker(sender: str) -> str:
    """Map an export sender to an explicit transcript tag: human = the author (signal),
    everything else = the other side (the assistant, the response-function conditioning)."""
    return "Gerard" if sender == "human" else "Assistant"


def build_dialogue_transcripts(repo_root: Path | str, raw_root: str = RAW_ROOT) -> list[str]:
    """Normalise every Claude-export ``conversations.json`` into per-conversation, speaker-tagged
    plain-text transcripts under a sibling ``_exploded/`` dir - the dialogue-shard working units.

    Why a derived transcript and not the raw JSON: a 91 MB single-array export is one opaque blob to
    a char-range chunker, and a byte slice of it is unparseable. Exploding to one transcript per
    conversation gives the sharder real, parseable, turn-windowable units that carry EXPLICIT speaker
    attribution (``@@Gerard`` his turn = signal, ``@@Assistant`` the other side). The ORIGINAL JSON is
    left untouched as verbatim ground truth (recovery is two-tier: transcript working copy + the
    original); the transcripts live under the gitignored raw tree, so soul-class never enters git.

    Mechanical: no LLM, no content returned to the caller - only the list of written relative paths.
    Idempotent + deterministic (index-named, no clock); re-running overwrites identically."""
    repo_root = Path(repo_root)
    root = repo_root / raw_root
    written: list[str] = []
    if not root.exists():
        return written
    seen: set[str] = set()
    for src in sorted(root.rglob("conversations.json")):
        fp = _fingerprint(src)
        if fp and fp in seen:
            continue  # identical re-landing: explode the canonical copy only
        seen.add(fp)
        try:
            data = json.loads(src.read_text(encoding="utf-8", errors="replace"))
        except (ValueError, OSError):
            continue
        if not isinstance(data, list):
            continue
        out_dir = src.parent / "_exploded"
        out_dir.mkdir(parents=True, exist_ok=True)
        for idx, conv in enumerate(data):
            msgs = conv.get("chat_messages") or []
            if not msgs:
                continue
            lines = [f"# claude-chat conversation {idx:04d}",
                     f"# title: {conv.get('name', '')}",
                     f"# created: {conv.get('created_at', '')} · messages: {len(msgs)}", ""]
            for m in msgs:
                tag = _claude_speaker(m.get("sender", ""))
                atts, files = m.get("attachments") or [], m.get("files") or []
                note = f"  [+{len(atts)} attachments, {len(files)} files]" if (atts or files) else ""
                lines += [f"@@{tag}{note}", (m.get("text") or "").strip(), ""]
            dest = out_dir / f"conv_{idx:04d}.txt"
            dest.write_text("\n".join(lines), encoding="utf-8")
            written.append(str(dest.relative_to(repo_root)).replace("\\", "/"))
    return written


def _chunks_for(path: Path, text: str) -> list[tuple[int, int, str]]:
    ext = path.suffix.lower()
    if ext == ".tex":
        return _chunk_tex(text)
    if ext == ".txt" and text[:13] == "# claude-chat":
        return _chunk_dialogue(text)
    if ext == ".txt" and ("whatsapp" in path.name.lower() or path.parent.name and
                          re.search(r"\d{1,2}[:/]\d{2}", text[:400])):
        return _chunk_lines(text)
    return _chunk_generic(text)


# ---------------------------------------------------------------------------
# the shard - one entry per chunk, sealed (no content, only a char range + structural label)
# ---------------------------------------------------------------------------

def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _fingerprint(path: Path) -> str:
    """A cheap content fingerprint (size + head/tail hash) to dedupe identical re-landings without
    reading whole 90 MB+ files. Two landings of the same export collide here and are sharded once."""
    import hashlib
    try:
        size = path.stat().st_size
        with path.open("rb") as f:
            head = f.read(65536)
            if size > 131072:
                f.seek(-65536, 2)
                tail = f.read(65536)
            else:
                tail = b""
        return f"{size}:{hashlib.sha1(head + tail).hexdigest()}"
    except OSError:
        return ""


def content_hash(text: str) -> str:
    """Content-hash identity for a chunk's MATERIALIZED text - the same identical-bytes-collapse
    law ``_fingerprint`` applies to a re-landed raw source, extended downstream to anything a
    staging step writes to disk. Two stagings of the same chunk (same source char-range,
    reconstructed identically) hash identically, wherever they are written.

    Full-content SHA1: staged chunks are small (``_TARGET`` ~6000 chars), so unlike
    ``_fingerprint`` (head/tail, for 90MB+ raw exports) there is no cost reason to sample."""
    import hashlib
    return hashlib.sha1(text.encode("utf-8", errors="replace")).hexdigest()


def materialized_index(repo_root: Path | str, shard_root: str = "archive/soul_dump/_shard") -> dict[str, str]:
    """content_hash -> first (canonical) relpath, over every ``.txt`` chunk already materialized
    under ANY existing shard output directory (``_shard/<name>/*.txt``). A staging step reads this
    BEFORE writing a new chunk file: a chunk whose content already lives somewhere collapses to
    that one canonical path instead of duplicating bytes under a second directory.

    The store's own law, applied to the failure FIBRE_CENSUS 2026-08-19 found (WO-20260820-chat-
    shard-dedup): 422 duplicate leaves - the same conversations staged under both
    ``_shard/claude_smoke/`` and ``_shard/scaled_claude/``, byte-identical because both were
    reconstructed from the same underlying chunk id."""
    repo_root = Path(repo_root)
    root = repo_root / shard_root
    canonical: dict[str, str] = {}
    if not root.exists():
        return canonical
    for p in sorted(root.rglob("*.txt")):
        if not p.is_file() or p.name == "_manifest.json":
            continue
        text = _read(p)
        if not text:
            continue
        h = content_hash(text)
        canonical.setdefault(h, str(p.relative_to(repo_root)).replace("\\", "/"))
    return canonical


def _category(rel: str) -> str:
    """The dump stream a source belongs to: chat_logs / personal_writing / claude_chats / ...
    (the segment directly under ``raw/``, where the landing put each stream)."""
    parts = rel.split("/")
    if "raw" in parts:
        i = parts.index("raw")
        if i + 1 < len(parts):
            return parts[i + 1]
    return parts[-2] if len(parts) > 1 else "root"


def shard_tree(repo_root: Path | str, raw_root: str = RAW_ROOT) -> list[dict[str, Any]]:
    """Shard every landed text source into sealed chunk nodes. JSON is treated as one opaque source
    (streamed-chunked by size) - a huge conversations.json is not loaded into a parser here; its
    char-range chunks are addressed and re-read on demand. Binaries are name-only nodes."""
    repo_root = Path(repo_root)
    root = repo_root / raw_root
    shards: list[dict[str, Any]] = []
    if not root.exists():
        return shards
    build_dialogue_transcripts(repo_root, raw_root)  # explode Claude exports into shardable transcripts first
    seen_fp: dict[str, str] = {}  # content fingerprint -> first (canonical) rel; dedupe identical re-landings
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        rel = str(path.relative_to(repo_root)).replace("\\", "/")
        name = path.name.lower()
        # Claude-export metadata / the dialogue SOURCE blob / prompt-template dirs: provenance asset
        # nodes only, never text-chunked (the dialogue itself rises via the _exploded transcripts).
        is_meta = (name in _META_JSON or name in _DIALOGUE_SOURCE
                   or any(p in _META_DIRS for p in path.parts))
        if path.suffix.lower() not in _TEXT_EXT or is_meta:
            label = ("claude metadata (name-only)" if name in _META_JSON
                     else "dialogue source - exploded to transcripts" if name in _DIALOGUE_SOURCE
                     else "prompt-template (name-only)" if any(p in _META_DIRS for p in path.parts)
                     else "binary asset (name-only)")
            shards.append({"id": f"{rel}#asset", "source": rel, "start": 0, "end": 0,
                           "n_chars": path.stat().st_size, "kind": path.suffix.lstrip(".") or "asset",
                           "label": label, "category": _category(rel), "axes": {}})
            continue
        fp = _fingerprint(path)  # an identical re-landing of a text source is chunked once
        if fp and fp in seen_fp:
            shards.append({"id": f"{rel}#dup", "source": rel, "start": 0, "end": 0,
                           "n_chars": path.stat().st_size, "kind": path.suffix.lstrip("."),
                           "label": f"duplicate of {seen_fp[fp]} (name-only)",
                           "category": _category(rel), "axes": {}})
            continue
        if fp:
            seen_fp[fp] = rel
        text = _read(path)
        for i, (a, b, label) in enumerate(_chunks_for(path, text)):
            shards.append({"id": f"{rel}#{i}", "source": rel, "start": a, "end": b,
                           "n_chars": b - a, "kind": path.suffix.lstrip("."), "label": label,
                           "category": _category(rel), "axes": {}})
    return shards


def write_local_index(repo_root: Path | str, shards: list[dict[str, Any]]) -> Path:
    """Persist the sealed chunk index - GITIGNORED, beside the raw. The rich layer that enables
    recovery; never committed, so soul-class never enters git."""
    repo_root = Path(repo_root)
    out = repo_root / LOCAL_INDEX
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        for sh in shards:
            f.write(json.dumps(sh, ensure_ascii=False) + "\n")
    return out


def load_local_index(repo_root: Path | str) -> list[dict[str, Any]]:
    repo_root = Path(repo_root)
    p = repo_root / LOCAL_INDEX
    if not p.exists():
        return []
    return [json.loads(ln) for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip()]


def reconstruct(repo_root: Path | str, chunk_id: str, shards: list[dict[str, Any]] | None = None) -> str:
    """Re-read the exact source char range a chunk points at - the grade-2 reconstruction. LOCAL only:
    returns "" if the raw is absent (a fresh clone has no gitignored raw, so it recovers nothing)."""
    repo_root = Path(repo_root)
    shards = shards if shards is not None else load_local_index(repo_root)
    by_id = {s["id"]: s for s in shards}
    sh = by_id.get(chunk_id)
    if not sh or sh["end"] <= sh["start"]:
        return ""
    text = _read(repo_root / sh["source"])
    return text[sh["start"]:sh["end"]]


def iter_chunk_text(repo_root: Path | str, shards: list[dict[str, Any]]) -> Iterator[tuple[str, str]]:
    """Yield (chunk_id, text) for sealed subs to read. Used ONLY inside a sealed sub-Eigen's context,
    never the orchestrator's - the anti-overwhelm guarantee."""
    repo_root = Path(repo_root)
    for sh in shards:
        if sh["end"] > sh["start"]:
            yield sh["id"], reconstruct(repo_root, sh["id"], shards)


# ---------------------------------------------------------------------------
# the committed manifest - structural ONLY (counts + discovered axis names), never content
# ---------------------------------------------------------------------------

def manifest(shards: list[dict[str, Any]]) -> dict[str, Any]:
    """A content-free structural summary safe to commit: chunk counts per category/kind and the set
    of axis NAMES that have been generated (the dimensions, not their values)."""
    cats: dict[str, int] = {}
    kinds: dict[str, int] = {}
    sources: set[str] = set()
    axes: set[str] = set()
    for sh in shards:
        cats[sh["category"]] = cats.get(sh["category"], 0) + 1
        kinds[sh["kind"]] = kinds.get(sh["kind"], 0) + 1
        sources.add(sh["source"])
        axes.update((sh.get("axes") or {}).keys())
    return {
        "chunks": len(shards), "sources": len(sources),
        "by_category": dict(sorted(cats.items(), key=lambda kv: -kv[1])),
        "by_kind": dict(sorted(kinds.items(), key=lambda kv: -kv[1])),
        "axes_discovered": sorted(axes),
    }


def default_repo_root() -> Path:
    return source_tree()


def main(argv: list[str]) -> int:
    import sys
    try:
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
    except (AttributeError, ValueError):
        pass
    cmd = argv[0] if argv else "build"
    root = default_repo_root()
    if cmd == "build":
        shards = shard_tree(root)
        write_local_index(root, shards)
        print(json.dumps(manifest(shards), ensure_ascii=False, indent=2))
        return 0
    if cmd == "reconstruct" and len(argv) > 1:
        print(reconstruct(root, argv[1]))
        return 0
    print("usage: soul_shard [build | reconstruct <chunk_id>]")
    return 2


if __name__ == "__main__":
    import sys
    raise SystemExit(main(sys.argv[1:]))
