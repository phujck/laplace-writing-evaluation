"""Leg D template organ — the gate <-> emitter <-> manuscript AGREEMENT + the seal.

The recurring steer: the .tex template is REVTeX4-2 based with the eigen house
layer (``eigen-revtex``). Three parties must agree:

* the GATE   -- ``tex_template.check_template`` (REVTeX4-2 base + the house layer)
* the EMITTER -- ``tex_backend.render_preamble`` reading the typography profile
* the MANUSCRIPT -- the shipped whitepaper ``main.tex``

Before this mechanisation the emitter listed the layer's packages RAW (no
``\\usepackage{eigen-revtex}``), so a pipeline-emitted preamble failed its own
gate. The agreement tests are the fixed point that ends the recurrence.

THE SEAL (corrected 2026-07-10, the author). An earlier retemplate stripped the
EigenEngine branding wholesale and a "cringe seal" test forbade the whole
signature (wordmark, colophon, fancyhdr, titlesec, ...). That was WRONG. The
author's steer: the branding he keeps; the ONLY cringe is the authorship-DENIAL
sign-off ("generated by EigenEngine ... wrote none of its words"). EigenEngine is
the TOOL identity in the masthead, never an authorship claim - the author is
Gerard McCaul. So the seal is inverted here:

* it FORBIDS the authorship-denial (``\\eigensign`` and its text) in the house
  layer, the emitted preamble and the whitepaper source; and
* it REQUIRES the branding PRESENT in the house layer (wordmark + colophon +
  coloured section numbers).
"""
from pathlib import Path

from laplace.pipeline import tex_backend, tex_template

REPO = Path(__file__).resolve().parents[1]
WHITEPAPER_MAIN = (REPO / "synthetics papers" / "subset-sum-itqde"
                   / "manuscript" / "whitepaper" / "main.tex")
TEMPLATE_STY = REPO / "templates" / "eigen-revtex" / "eigen-revtex.sty"
WHITEPAPER_STY = (REPO / "synthetics papers" / "subset-sum-itqde"
                  / "manuscript" / "whitepaper" / "eigen-revtex.sty")


def _rendered(src: str) -> str:
    """Comment-stripped, lower-cased — the content that actually renders."""
    return tex_template._strip_tex_comments(src).lower()


# --- the AGREEMENT: emitter output passes the gate --------------------------

def test_emitted_preamble_passes_check_template():
    """The mechanisation: the profile-driven emitter produces a preamble that
    the gate accepts. This is the invariant whose absence caused the recurrence."""
    profile = tex_backend.load_profile()
    preamble = tex_backend.render_preamble(profile, {})
    # a minimal body so check_template sees a whole preamble
    result = tex_template.check_template(preamble + "\n\\begin{document}\n"
                                         "\\title{X}\\maketitle\n\\end{document}\n")
    assert result["pass"] is True, result["findings"]
    assert result["documentclass"] == tex_template.BASE_CLASS
    assert result["house_layer"] is True
    assert result["missing_required"] == []


def test_emitted_preamble_emits_layer_and_trims_provided_packages():
    """The emitter emits ``\\usepackage{eigen-revtex}`` and DROPS every package
    the layer provides (LAYER_PROVIDES is the single trim source), so the layer
    and the emitter cannot drift apart."""
    profile = tex_backend.load_profile()
    preamble = tex_backend.render_preamble(profile, {})
    assert f"\\usepackage{{{tex_template.HOUSE_LAYER}}}" in preamble
    # none of the layer-provided packages appear as their own \usepackage line
    for pkg in tex_template.LAYER_PROVIDES:
        assert f"\\usepackage{{{pkg}}}" not in preamble, pkg
        assert f"]{{{pkg}}}" not in preamble, pkg   # nor the optioned form


def test_whitepaper_main_tex_passes_check_template():
    """The manuscript half of the agreement: the shipped whitepaper source is on
    the REVTeX4-2 base and carries the house layer."""
    result = tex_template.check_template(WHITEPAPER_MAIN.read_text(encoding="utf-8"))
    assert result["pass"] is True, result["findings"]
    assert result["documentclass"] == tex_template.BASE_CLASS
    assert result["house_layer"] is True
    assert result["missing_required"] == []


def test_colocated_layer_is_in_sync_with_the_source_of_truth():
    """The whitepaper's co-located ``eigen-revtex.sty`` duplicates the source
    layer by COPY; its body (below its 'co-located copy' banner) must match the
    template verbatim, or the two silently drift."""
    template = TEMPLATE_STY.read_text(encoding="utf-8")
    colocated = WHITEPAPER_STY.read_text(encoding="utf-8")
    marker = "% eigen-revtex.sty - the EigenEngine house layer"
    assert marker in colocated, "co-located copy lost the layer body"
    body = colocated[colocated.index(marker):]
    assert body == template, "co-located eigen-revtex.sty drifted from the template"


# --- the SEAL: forbid the authorship-denial, require the branding -----------

#: the ONLY cringe: the authorship-DENIAL sign-off. EigenEngine is a tool
#: identity, never an author. Matched case-insensitively on the COMMENT-STRIPPED
#: source (a provenance comment naming what was dropped is not cringe; only
#: rendered content counts).
AUTHORSHIP_DENIAL = {
    "eigensign sign-off macro": "eigensign",
    "wrote-none-of-its-words denial": "wrote none of its words",
    "generated-by authorship claim": "generated by",
}

#: the branding the author KEEPS - it must be present in the house layer.
REQUIRED_BRANDING = {
    "eigenengine wordmark": "eigenengine",
    "eigen-colophon mark": "eigencolophon",
    "coloured section numbers": "seccntformat",
}


def test_no_authorship_denial_in_template_sty():
    rendered = _rendered(TEMPLATE_STY.read_text(encoding="utf-8"))
    hits = {name: tok for name, tok in AUTHORSHIP_DENIAL.items() if tok in rendered}
    assert not hits, f"authorship-denial leaked into the house layer: {hits}"


def test_no_authorship_denial_in_whitepaper_main_tex():
    rendered = _rendered(WHITEPAPER_MAIN.read_text(encoding="utf-8"))
    hits = {name: tok for name, tok in AUTHORSHIP_DENIAL.items() if tok in rendered}
    assert not hits, f"authorship-denial leaked into the whitepaper main.tex: {hits}"


def test_no_authorship_denial_in_emitted_preamble():
    profile = tex_backend.load_profile()
    rendered = _rendered(tex_backend.render_preamble(profile, {}))
    hits = {name: tok for name, tok in AUTHORSHIP_DENIAL.items() if tok in rendered}
    assert not hits, f"authorship-denial leaked into the emitted preamble: {hits}"


def test_branding_present_in_template_sty():
    """The wordmark, the eigen-colophon and coloured section numbers are the
    signature the author keeps; the house layer must carry all three."""
    rendered = _rendered(TEMPLATE_STY.read_text(encoding="utf-8"))
    missing = {name: tok for name, tok in REQUIRED_BRANDING.items()
               if tok not in rendered}
    assert not missing, f"branding missing from the house layer: {missing}"


def test_whitepaper_hypersetup_is_revision_neutral():
    """The stale r1/branch strings are gone from pdfsubject/pdfkeywords; the
    version stamp is applied at finalize time (C1), not carried in source."""
    src = WHITEPAPER_MAIN.read_text(encoding="utf-8")
    for stale in ("-r1", "-r2", "incumbent r1", "close-loop-at-origin",
                  "version 2026-07-10"):
        assert stale not in src, f"stale revision string still in source: {stale!r}"
