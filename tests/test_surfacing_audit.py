def test_real_repo_has_no_surfacing_violations():
    rep = sa.audit(REPO_ROOT)
    assert rep["violations"] == [], (
        "pipeline reads files invisible to a fresh clone:\n"
        + "\n".join(f"  {v['path']}  [{v['rule']}]" for v in rep["violations"])
    )
    assert rep["classified"]["violations"] == 0


def test_real_repo_audit_exit_code_is_zero():
    assert sa.main([str(REPO_ROOT), "-q"]) == 0


def test_real_repo_surface_is_populated_and_multi_project():
    rep = sa.audit(REPO_ROOT)
    # the surface is really derived (registry + static), not empty
    assert rep["read_surface_size"] > 50
    assert len(rep["read_surface"]["projects"]) >= 5
    assert rep["gitignore_rule_count"] > 50


def test_latexmk_artifacts_classify_reconstructable(tmp_path):
    """The engine must call latexmk build artifacts reconstructable — proved on a
    CONTROLLED fixture so the assertion holds in a fresh clone (which carries no
    build artifacts). An ignored ``.aux``/``.bbl``/``.fls`` present on disk under a
    documented latexmk rule classifies reconstructable via the TeX backstop."""
    root = tmp_path / "repo"
    (root / "build").mkdir(parents=True)
    _git(root, "init", "-q")
    _git(root, "config", "user.email", "t@t")
    _git(root, "config", "user.name", "t")
    (root / ".gitignore").write_text(
        "# latexmk build artifacts, regenerated by every compile\nbuild/*\n",
        encoding="utf-8")
    names = ("main.aux", "main.bbl", "main.fls")
    for n in names:
        (root / "build" / n).write_text("x\n", encoding="utf-8")
    (root / "keep.txt").write_text("x\n", encoding="utf-8")
    _git(root, "add", ".gitignore", "keep.txt")
    _git(root, "commit", "-q", "-m", "seed")

    tracked = sa.tracked_files(root)
    ignored = sa.ignored_present_files(root)
    gi = sa.GitignoreModel(root)
    attribution = sa.attribute_rules(root, [f"build/{n}" for n in names])
    is_recon = lambda rel: gi.is_reconstructable(rel, attribution)[0]  # noqa: E731
    for n in names:
        rel = f"build/{n}"
        assert rel in ignored
        assert sa.classify_path(rel, tracked, ignored, is_recon) == "reconstructable"


def test_real_repo_latexmk_artifacts_reconstructable_when_present():
    """When THIS working tree carries latexmk artifacts (a local build), they sit
    inside the read-surface intersection and are classified reconstructable, never
    missed. SKIPPED on a fresh clone with no build artifacts — the classification
    itself is proved unconditionally in the fixture test above."""
    rep = sa.audit(REPO_ROOT)
    tex = [r for r in rep["intersection"] if r["path"].endswith((".aux", ".bbl", ".fls"))]
    if not tex:
        pytest.skip("no latexmk artifacts in the working tree (fresh clone) — the "
                    "reconstructable classification is proved by "
                    "test_latexmk_artifacts_classify_reconstructable")
    assert all(r["class"] == "reconstructable" for r in tex)
