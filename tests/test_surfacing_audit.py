"""The surfacing audit as a gate (Leg C bite C2).

Two things are proven here:

1. THE CLASSIFIER discriminates the three classes on a controlled fixture git tree —
   one tracked file, one reconstructable file (an ignored artifact whose ``.gitignore``
   comment documents its regen), one planted violation (ignored, read, no regen path).
   The reconstructable/violation split is the whole point, so it is exercised on the
   REAL :class:`GitignoreModel` + :func:`classify_path`, not a mock.

2. THE REPO is clean: running the audit against THIS working tree surfaces zero
   VIOLATIONs — nothing the pipeline reads at run time is invisible to a fresh clone.

Plus the exit-code contract (0 = clean, 2 = violations) end-to-end through ``main``.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "scripts"))

import surfacing_audit as sa  # noqa: E402


# ---------------------------------------------------------------------------
# fixture git tree
# ---------------------------------------------------------------------------


def _git(root: Path, *args: str) -> None:
    subprocess.run(["git", "-C", str(root), *args], check=True,
                   capture_output=True, text=True)


@pytest.fixture
def fixture_tree(tmp_path: Path) -> Path:
    """A tiny git repo: 1 tracked, 1 reconstructable (documented regen), 1 violation."""
    root = tmp_path / "repo"
    root.mkdir()
    _git(root, "init", "-q")
    _git(root, "config", "user.email", "t@t")
    _git(root, "config", "user.name", "t")

    # .gitignore: the *.pdf comment DOCUMENTS regen; the *.secret rule does NOT.
    (root / ".gitignore").write_text(
        "# compiled render, regenerated by the build\n"
        "*.pdf\n"
        "\n"
        "# sensitive material, present only on this machine\n"
        "*.secret\n",
        encoding="utf-8",
    )
    (root / "keep.txt").write_text("tracked source\n", encoding="utf-8")
    (root / "out.pdf").write_text("%PDF fake\n", encoding="utf-8")          # reconstructable
    (root / "planted.secret").write_text("only-here\n", encoding="utf-8")   # violation

    _git(root, "add", ".gitignore", "keep.txt")
    _git(root, "commit", "-q", "-m", "seed")
    return root


def _is_recon_for(root: Path):
    gi = sa.GitignoreModel(root)
    attribution = sa.attribute_rules(root, ["out.pdf", "planted.secret"])
    return lambda rel: gi.is_reconstructable(rel, attribution)[0], gi


def test_classifier_three_way_on_fixture(fixture_tree: Path):
    root = fixture_tree
    tracked = sa.tracked_files(root)
    ignored = sa.ignored_present_files(root)
    is_recon, _gi = _is_recon_for(root)

    assert "keep.txt" in tracked
    assert {"out.pdf", "planted.secret"} <= ignored

    assert sa.classify_path("keep.txt", tracked, ignored, is_recon) == "tracked"
    assert sa.classify_path("out.pdf", tracked, ignored, is_recon) == "reconstructable"
    assert sa.classify_path("planted.secret", tracked, ignored, is_recon) == "violation"


def test_gitignore_model_reads_regen_from_comments(fixture_tree: Path):
    gi = sa.GitignoreModel(fixture_tree)
    by_pat = {r["pattern"]: r for r in gi.rules}
    assert by_pat["*.pdf"]["regenerable"] is True       # comment says "regenerated"
    assert by_pat["*.secret"]["regenerable"] is False   # comment names no regen path


def test_classify_path_pure_branches():
    """The pure classifier logic, isolated from git (fake is_reconstructable)."""
    tracked, ignored = {"a"}, {"b", "c"}
    assert sa.classify_path("a", tracked, ignored, lambda r: False) == "tracked"
    assert sa.classify_path("b", tracked, ignored, lambda r: True) == "reconstructable"
    assert sa.classify_path("c", tracked, ignored, lambda r: False) == "violation"
    # absent + untracked + not-ignored => a run-time artifact the pipeline writes
    assert sa.classify_path("z", tracked, ignored, lambda r: False) == "reconstructable"


def test_end_to_end_biter_exit_2(tmp_path: Path):
    """A planted, ignored, read-surface file with no regen path => exit 2.

    The read-surface here is driven by a STATIC path literal in a scanned workflow
    script, so the biter is exercised through the full ``audit`` + ``main`` path
    without depending on the registry.
    """
    root = tmp_path / "repo"
    (root / "profiles" / "thing").mkdir(parents=True)
    (root / ".claude" / "workflows").mkdir(parents=True)
    _git(root, "init", "-q")
    _git(root, "config", "user.email", "t@t")
    _git(root, "config", "user.name", "t")

    (root / ".gitignore").write_text(
        "# sensitive material\nprofiles/**/*.yaml\n", encoding="utf-8"
    )
    # a scanned workflow that READS a concrete repo-relative config path
    (root / ".claude" / "workflows" / "w.py").write_text(
        'CONFIG = "profiles/thing/config.yaml"\n', encoding="utf-8"
    )
    # the config is present on disk but ignored + has no documented regen path
    (root / "profiles" / "thing" / "config.yaml").write_text("k: v\n", encoding="utf-8")
    (root / "keep.txt").write_text("x\n", encoding="utf-8")
    _git(root, "add", ".gitignore", ".claude/workflows/w.py", "keep.txt")
    _git(root, "commit", "-q", "-m", "seed")

    rep = sa.audit(root)
    assert "profiles/thing/config.yaml" in rep["read_surface"]["static_literals"]
    assert [v["path"] for v in rep["violations"]] == ["profiles/thing/config.yaml"]
    assert sa.main([str(root), "-q"]) == 2


