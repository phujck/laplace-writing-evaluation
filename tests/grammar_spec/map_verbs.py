def concept_block() -> str:
    data = rows()
    concepts = sorted({r["concept"] for r in data})
    pairs = sorted({(r["verb"], r["concept"]) for r in data})
    lines = [CONCEPT_BEGIN,
             "CONCEPTS: frozenset = frozenset({"]
    for concept in concepts:
        lines.append('    "%s",' % concept)
    lines.append("})")
    lines.append("VERB_CONCEPTS: frozenset = frozenset({")
    for verb, concept in pairs:
        lines.append('    ("%s", "%s"),' % (verb, concept))
    lines.append("})")
    lines.append(CONCEPT_END)
    return "\n".join(lines)


def _splice(text: str, begin: str, end: str, body: str) -> str:
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    return head + begin + "\n\n" + body + "\n\n" + end + tail


def main() -> int:
    data = rows()
    leaf = [r for r in data if r["level"] == "leaf"]
    nested = [r for r in data if r["level"] == "nested"]
    with (HERE / "mapping.csv").open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(data[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(data)
    counts: dict[str, int] = {}
    concepts: set[str] = set()
    for r in data:
        counts[r["verb"]] = counts.get(r["verb"], 0) + 1
        concepts.add(r["concept"])
    print("leaf verbs mapped: %d (audit: 131)" % len(leaf))
    print("nested sub-verbs mapped: %d (audit: 21)" % len(nested))
    print("status rows (one leaf verb split by its payload enum): %d"
          % len([r for r in data if r["level"] == "status"]))
    print("post-audit extensions: %d" % len([r for r in data if r["level"] == "extension"]))
    print("total: %d" % len(data))
    print("verbs used: %s" % sorted(counts))
    print("per verb: %s" % dict(sorted(counts.items(), key=lambda kv: -kv[1])))
    print("distinct concepts: %d" % len(concepts))
    print("distinct home kinds in guards: %d"
          % len({h for value in GUARD_HOME.values() for h in value.split("|")}))
    if GRAMMAR.is_file():
        text = GRAMMAR.read_text(encoding="utf-8")
        if BEGIN in text and END in text:
            text = _splice(text, BEGIN, END, table(data))
            print("spliced %d mapping rows into %s" % (len(data), GRAMMAR.name))
        else:
            print("GRAMMAR.md has no mapping markers", file=sys.stderr)
        if HOME_BEGIN in text and HOME_END in text:
            body = home_table()
            text = _splice(text, HOME_BEGIN, HOME_END, body)
            print("spliced %d home rows into %s" % (body.count(chr(10)) - 1, GRAMMAR.name))
        else:
            print("GRAMMAR.md has no home markers", file=sys.stderr)
        if OBTAIN_BEGIN in text and OBTAIN_END in text:
            body = obtain_table()
            text = _splice(text, OBTAIN_BEGIN, OBTAIN_END, body)
            print("spliced %d obtain rows into %s" % (body.count(chr(10)) - 1, GRAMMAR.name))
        else:
            print("GRAMMAR.md has no obtain markers", file=sys.stderr)
        if COUNT_BEGIN in text and COUNT_END in text:
            text = _splice(text, COUNT_BEGIN, COUNT_END, coverage_paragraph())
            print("spliced the coverage counts into %s" % GRAMMAR.name)
        else:
            print("GRAMMAR.md has no coverage markers", file=sys.stderr)
        GRAMMAR.write_text(text, encoding="utf-8")
    if MODULE.is_file():
        module = MODULE.read_text(encoding="utf-8")
        if CONCEPT_BEGIN in module and CONCEPT_END in module:
            head, rest = module.split(CONCEPT_BEGIN, 1)
            _, tail = rest.split(CONCEPT_END, 1)
            module = head + concept_block() + tail
            MODULE.write_text(module, encoding="utf-8")
            c = coverage_counts()
            print("spliced %d concepts and %d (verb, concept) pairs into grammar.py"
                  % (c["concepts"], c["pairs"]))
        else:
            print("grammar.py has no concept markers", file=sys.stderr)
    print("coverage counts: %s" % coverage_counts())
    return 0


