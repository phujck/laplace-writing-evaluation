def rows() -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    unmapped: list[tuple[str, str]] = []
    seen_nested: set[str] = set()
    for row in csv.DictReader(MATRIX.open()):
        key = (row["operation"], row["verb"])
        if key not in M:
            unmapped.append(key)
            continue
        verb, concept = M[key]
        guards = [g for g in row["guard_fields"].split("|") if g]
        required = {g for g in row["required_guard_fields"].split("|") if g}
        homes, missing = [], []
        for guard in guards:
            key = (row["operation"], guard)
            if key in NOT_A_GUARD:
                homes.append("NONE (%s)" % NOT_A_GUARD[key])
                continue
            home = GUARD_HOME.get(key)
            if home is None:
                missing.append(guard)
                continue
            homes.append(home + ("" if guard in required else "?"))
        if missing:
            unmapped.append((row["operation"], "guard:" + ",".join(missing)))
        out.append({"operation": row["operation"], "old_verb": row["verb"],
                    "verb": verb, "concept": concept,
                    "old_guards": "/".join(guards) or "-",
                    "homes": "/".join(dict.fromkeys(homes)) or "-",
                    "owner": row["owner_module"].replace("src/laplace/", ""),
                    "level": "leaf", "because": ""})
        for discriminator, sverb, sconcept, because in STATUS_SPLIT.get(
                (row["operation"], row["verb"]), ()):
            out.append({"operation": row["operation"], "old_verb": discriminator,
                        "verb": sverb, "concept": sconcept,
                        "old_guards": "/".join(guards) or "-",
                        "homes": "/".join(dict.fromkeys(homes)) or "-",
                        "owner": row["owner_module"].replace("src/laplace/", ""),
                        "level": "status", "because": because})
        for nested in (n for n in row["nested_verbs"].split("|") if n):
            if nested in seen_nested:
                continue
            seen_nested.add(nested)
            if nested not in NESTED:
                unmapped.append((row["operation"], nested))
                continue
            nverb, nconcept = NESTED[nested]
            out.append({"operation": row["operation"] + " " + row["verb"],
                        "old_verb": nested, "verb": nverb, "concept": nconcept,
                        "old_guards": "/".join(guards) or "-",
                        "homes": "/".join(dict.fromkeys(homes)) or "-",
                        "owner": row["owner_module"].replace("src/laplace/", ""),
                        "level": "nested", "because": ""})
    out.extend(dict(row) for row in EXTENSIONS)
    if unmapped:
        raise SystemExit("unassigned audited verbs or guards: %r" % (unmapped,))
    bad = [r for r in out if r["verb"] not in VERBS]
    if bad:
        raise SystemExit("verb outside the alphabet: %r" % (bad,))
    return out


def table(data: list[dict[str, str]]) -> str:
    lines = ["| # | old name (operation / verb) | grammar verb | concept | old guard name(s) | home kind(s) | owner |",
             "|---|---|---|---|---|---|---|"]
    for i, r in enumerate(data, 1):
        name = "`%s` / `%s`" % (r["operation"], r["old_verb"])
        lines.append("| %d | %s | `%s` | `%s` | `%s` | `%s` | `%s` |"
                     % (i, name, r["verb"], r["concept"], r["old_guards"],
                        r["homes"], r["owner"]))
    return "\n".join(lines)


def _grammar():
    """The grammar module, installed or not --- `laplace.core.grammar` first, then the file
    beside this script.  A bare `import grammar` can resolve to a sibling DIRECTORY named
    `grammar` as an empty namespace package, which is how this packet's own first install
    run produced `module 'grammar' has no attribute 'HOME_KINDS'`."""
    try:
        from laplace.core import grammar as mod           # type: ignore
        if hasattr(mod, "HOME_KINDS"):
            return mod
    except Exception:
        pass
    sys.path.insert(0, str(HERE))
    import grammar as mod                            # type: ignore
    assert hasattr(mod, "HOME_KINDS"), (
        "%r is not the grammar module; a directory named `grammar` is shadowing it"
        % (getattr(mod, "__file__", mod),))
    return mod


def home_table() -> str:
    """Render HOME_KINDS: one row per home kind, one minting rule each."""
    grammar = _grammar()
    lines = ["| home kind | home id | bytes digested (the one minting rule) | recipe | `identity()` obtains it | minted today at | asked for as | published as | the one read |",
             "|---|---|---|---|---|---|---|---|---|"]
    for kind, home in grammar.HOME_KINDS.items():
        guards = ", ".join("`%s`" % g for g in home.guards_today) or "--"
        if home.guard_doors:
            guards += " (door: " + "; ".join(home.guard_doors) + ")"
        lines.append("| `%s` | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            kind, home.id_is, home.bytes, home.recipe,
            "**read**" if grammar.MINT_STATUS[kind] == "read" else "caller `value=`",
            home.source, guards,
            ", ".join("`%s`" % p for p in home.published_as) or "--",
            home.read or "--"))
    return "\n".join(lines)


def obtain_table() -> str:
    """Render the partition identity() really has: which homes a lane can get a token for.

    This is the answer to the question a lane asks first and could not answer from the
    round-1 spec without running the module: can I obtain this home's token, and if not,
    what exactly would close it?
    """
    grammar = _grammar()
    lines = ["| home kind | recipe | `identity(home)` | what would close it |",
             "|---|---|---|---|"]
    for kind in grammar.CALLER_VALUE:
        home = grammar.HOME_KINDS[kind]
        lines.append("| `%s` | %s | **caller must pass `value=`** | %s |"
                     % (kind, home.recipe, home.closes.strip()))
    return "\n".join(lines)


def coverage_counts() -> dict[str, int]:
    """Every number §7 and §2.1 state, computed from the rows, never typed."""
    grammar = _grammar()
    data = rows()
    homes = {h for value in GUARD_HOME.values() for h in value.split("|")}
    return {"leaf": len([r for r in data if r["level"] == "leaf"]),
            "nested": len([r for r in data if r["level"] == "nested"]),
            "extension": len([r for r in data if r["level"] == "extension"]),
            "total": len(data),
            "verbs": len({r["verb"] for r in data}),
            "concepts": len({r["concept"] for r in data}),
            "pairs": len({(r["verb"], r["concept"]) for r in data}),
            "guard_homes": len(homes),
            "home_kinds": len(grammar.HOME_KINDS),
            "obtainable": len(grammar.OBTAINABLE),
            "caller_value": len(grammar.CALLER_VALUE),
            "recipe_B": sum(1 for h in grammar.HOME_KINDS.values() if h.recipe == "B"),
            "recipe_J": sum(1 for h in grammar.HOME_KINDS.values() if h.recipe == "J"),
            "recipe_O": sum(1 for h in grammar.HOME_KINDS.values() if h.recipe == "O"),
            # recipe B homes whose own id IS the path, read straight from disk, against
            # the wired owner reads (one of which resolves a recipe-B file's path)
            "disk_B": sum(1 for k, h in grammar.HOME_KINDS.items()
                          if h.recipe == "B" and k not in grammar.OWNER_READS),
            "wired": len([k for k in grammar.OWNER_READS if k in grammar.OBTAINABLE]),
            "status": len([r for r in data if r["level"] == "status"]),
            "shims": 0}


