"""Prove that every `home` difference in a replay is one statement that moved.

    scripts/laplace-python tools/home_line_shift.py --rows <parity dir>/rows.jsonl \
        --old <base worktree> --new . --out <dir>

The oracle's `home` field is the `file:line` of the statement that raised.  A lane that
inserts a line above a `raise` moves it, and `HARNESS.md` says any `home` difference is a
behaviour change.  This checks the claim instead of arguing about it: for every row whose
only difference is `home`, it reads BOTH trees at BOTH line numbers and asserts

  * the two lines are the same statement, character for character after stripping, and
  * the refusal's class, error text and error type are identical on the two sides.

A row that fails either check is a real behaviour difference and is printed as such.  The
rows that pass are emitted as a scoped allow-list fragment --- one entry per row id,
allowing `home` on that row only --- so the allowance names 97 measured line shifts rather
than switching off a whole difference kind.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def line_at(tree: Path, citation: str) -> str:
    path, _, number = citation.rpartition(":")
    try:
        lines = (tree / path).read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        return "<unreadable: %s>" % exc
    index = int(number) - 1
    return lines[index].strip() if 0 <= index < len(lines) else "<past the end>"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rows", required=True)
    parser.add_argument("--old", required=True)
    parser.add_argument("--new", default=".")
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    old, new = Path(args.old).resolve(), Path(args.new).resolve()
    rows = [json.loads(line) for line in Path(args.rows).read_text(encoding="utf-8").splitlines()
            if line.strip()]

    shifts: dict[str, dict] = {}
    real: list[dict] = []
    other: list[dict] = []
    for row in rows:
        diffs = row.get("diffs") or []
        if not diffs:
            continue
        if diffs != ["home"]:
            other.append({"id": row["id"], "diffs": diffs})
            continue
        old_home, new_home = row["old"].get("home"), row["new"].get("home")
        old_line, new_line = line_at(old, old_home or ""), line_at(new, new_home or "")
        same_statement = bool(old_line) and old_line == new_line
        same_refusal = all(row["old"].get(key) == row["new"].get(key)
                           for key in ("class", "error", "error_type", "homes"))
        entry = {"id": row["id"], "operation": row["operation"], "source": row["source"],
                 "old_home": old_home, "new_home": new_home, "statement": old_line,
                 "same_statement": same_statement, "same_refusal": same_refusal,
                 "error": row["old"].get("error"),
                 "bytes_divergent_so_far": row.get("bytes_divergent_so_far")}
        if same_statement and same_refusal:
            shifts[row["id"]] = entry
        else:
            real.append(entry)

    statements = sorted({entry["statement"] for entry in shifts.values()})
    moves = sorted({(entry["old_home"], entry["new_home"]) for entry in shifts.values()})
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "home_line_shift.json").write_text(json.dumps(
        {"rows_examined": len(rows), "home_only_rows": len(shifts) + len(real),
         "verified_line_shifts": len(shifts), "real_home_differences": real,
         "rows_with_other_differences": other,
         "distinct_statements": statements, "distinct_moves": moves,
         "by_source": {source: sum(1 for e in shifts.values() if e["source"] == source)
                       for source in sorted({e["source"] for e in shifts.values()})},
         "by_operation": {operation: sum(1 for e in shifts.values()
                                         if e["operation"] == operation)
                          for operation in sorted({e["operation"] for e in shifts.values()})},
         "rows": shifts}, ensure_ascii=False, indent=1), encoding="utf-8")
    (out / "allow.home_shift.json").write_text(json.dumps(
        {"note": "Generated by tools/home_line_shift.py. One entry per row, allowing the "
                 "`home` difference on that row only, after reading BOTH trees at BOTH line "
                 "numbers and finding the same statement and the same refusal. The whole "
                 "`home` kind is NOT allowed: a home difference on any other row still "
                 "fails, and `class`, `error`, `homes` and `bytes` are never allowed here.",
         "kinds": [], "sources": {}, "operations": {},
         "rows": {row_id: ["home"] for row_id in sorted(shifts)}},
        ensure_ascii=False, indent=1), encoding="utf-8")

    print("rows examined %d; home-only differences %d, of which verified line shifts %d"
          % (len(rows), len(shifts) + len(real), len(shifts)))
    print("distinct statements behind every one of them: %r" % (statements,))
    print("distinct moves: %r" % (moves,))
    print("real home differences (a statement that is NOT the same): %d %r"
          % (len(real), [e["id"] for e in real][:5]))
    print("rows with any other difference kind: %d" % len(other))
    return 1 if real else 0


if __name__ == "__main__":
    raise SystemExit(main())
