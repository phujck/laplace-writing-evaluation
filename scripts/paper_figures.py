"""The data-face figures for the paper renders - every panel a projection of a banked
artifact, regenerated by running this script (the claims-ledger law extended to pixels).

fig_spectra   - the F28/C6 result: per-generator closure margins, self vs the physics
                corpora, read LIVE by the same instrument (mech_closure's geometry).
fig_ladders   - C1: the grade ladders counted MECHANICALLY from the regraded files
                (generators / rungs / unique papers), against the banked semantic cliff.
fig_economics - C3: the falling cost of the loop (numbers verbatim from claim C3).
fig_residue   - C7 + foldback.json: the eight drafted sections routing home through the
                projection cascade, against the known-home benchmark.

Outputs paper_eigen/figures/*.png (+ .pdf). Captions live with the manuscript; a caption
may claim only what its panel shows.
"""
import io
import json
import sys
from pathlib import Path

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "paper_eigen" / "figures"
STRUCT = ROOT / "collaborator_corpus" / "_structural"
SELF_RECORD = ROOT / "archive" / "self_record" / "_structural" / "self_record.json"

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

# embed TrueType/Type-42 fonts in the PDF emit, never matplotlib's Type-3 default
plt.rcParams.update({"pdf.fonttype": 42, "ps.fonttype": 42})

import re
import subprocess


def spectrum_margins(path: Path) -> list[float]:
    """Run the closure instrument itself on a structural file and read the margins off its
    table - the figure parses the instrument's output, never reimplements its geometry."""
    out = subprocess.run([sys.executable, str(ROOT / "scripts" / "mech_closure_lens.py"),
                          str(path)], capture_output=True, text=True, encoding="utf-8",
                         errors="replace", timeout=300).stdout
    return [float(m.group(2)) for m in
            re.finditer(r"\s(-?\d+\.\d+)\s+(-?\d+\.\d+)\s", out)]

INK = "#1a1a2e"
SELF_C = "#c0392b"
PHYS_C = "#2c6fad"
GRID = dict(color="#cccccc", lw=0.6, alpha=0.6)


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.tick_params(colors=INK, labelsize=9)


def save(fig, name):
    OUT.mkdir(parents=True, exist_ok=True)
    for ext in ("png", "pdf"):
        fig.savefig(OUT / f"{name}.{ext}", dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"  -> figures/{name}.png|.pdf")


def fig_spectra():
    """Margins per generator, the self vs every physics corpus - the C6 contrast, live."""
    keys = ["mccaul", "magann", "bondar", "booth", "totero", "balanov", "jacobs", "alanissila"]
    rows = []
    for k in keys:
        f = STRUCT / f"{k}.json"
        if not f.is_file():
            print(f"  spectra: {k} MISSING")
            continue
        margins = spectrum_margins(f)
        rows.append((k, margins))
        print(f"  spectra: {k} -> {len(margins)} generators")
    rows.append(("self record", spectrum_margins(SELF_RECORD)))

    fig, ax = plt.subplots(figsize=(7.2, 3.6))
    for i, (name, margins) in enumerate(rows):
        is_self = name == "self record"
        c = SELF_C if is_self else PHYS_C
        x = np.full(len(margins), i) + (np.random.default_rng(7).uniform(-.08, .08, len(margins)))
        ax.scatter(x, margins, s=26 if is_self else 14, color=c, alpha=.95 if is_self else .55,
                   zorder=3, edgecolors="none")
    ax.axhline(0, color=INK, lw=0.8)
    ax.axhline(0.025, color=SELF_C, lw=0.7, ls="--", alpha=0.6)
    ax.text(len(rows) - 0.4, 0.027, "0.025", fontsize=8, color=SELF_C)
    ax.set_xticks(range(len(rows)))
    ax.set_xticklabels([r[0] for r in rows], rotation=30, ha="right", fontsize=8.5)
    ax.set_ylabel("closure margin per generator", fontsize=9.5, color=INK)
    ax.grid(axis="y", **GRID)
    style(ax)
    save(fig, "fig_spectra")


def fig_ladders():
    """Grade sizes counted mechanically from the regraded files vs the banked cliff [C1]."""
    fig, ax = plt.subplots(figsize=(5.6, 3.8))
    for f in sorted(STRUCT.glob("*_regraded.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        gs = d["generators"]
        rungs = sum(len(g.get("rungs", [])) for g in gs)
        papers = len({p for g in gs for r in g.get("rungs", []) for p in r.get("papers", [])})
        ax.plot([0, 1, 2], [len(gs), max(rungs, 1), max(papers, 1)],
                marker="o", ms=3.5, lw=1.1, color=PHYS_C, alpha=.6)
    # the semantic-atomisation cliff on the same McCaul corpus, numbers verbatim from C1
    ax.plot([0, 1, 2, 3], [1, 7, 21, 383], marker="s", ms=4, lw=1.4,
            color=SELF_C, ls="--", label="semantic atomise-then-backfill (cliff) [C1]")
    ax.set_yscale("log")
    ax.set_xticks([0, 1, 2, 3])
    ax.set_xticklabels(["generators", "middle", "floor", "(cliff g3)"], fontsize=9)
    ax.set_ylabel("concepts per grade (log)", fontsize=9.5, color=INK)
    ax.legend(fontsize=8, frameon=False, loc="upper left")
    ax.grid(axis="y", **GRID)
    style(ax)
    save(fig, "fig_ladders")


def fig_economics():
    """The loop getting cheaper - every number verbatim from claim C3."""
    # C3: first corpus ~80 agents / 4 gate rounds; next two (from deposited operation
    # nodes) 17 agents / 0 rounds = 21%; whole wave 2: 7 corpora, ~210 agents, ONE judge pair.
    fig, ax = plt.subplots(figsize=(5.2, 3.4))
    stages = ["first corpus\n(McCaul)", "next two\n(Magann+Bondar)", "wave 2 mean\n(7 corpora)"]
    agents = [80, 17, 210 / 7]
    rounds = [4, 0, 0]
    bars = ax.bar(stages, agents, width=.55, color=[SELF_C, PHYS_C, PHYS_C], alpha=.85)
    for b, a, r in zip(bars, agents, rounds):
        ax.text(b.get_x() + b.get_width() / 2, b.get_height() + 2,
                f"{a:.0f} agents\n{r} gate rounds", ha="center", fontsize=8.5, color=INK)
    ax.set_ylabel("agents per corpus stage [C3]", fontsize=9.5, color=INK)
    ax.set_ylim(0, 100)
    ax.grid(axis="y", **GRID)
    style(ax)
    save(fig, "fig_economics")


def fig_residue():
    """The eight drafted sections folded back through the projection cascade (foldback.json),
    against the known-home benchmark absorbed=0.82 [C7]."""
    fb = json.loads((ROOT / "paper_eigen" / "_loop" / "foldback.json").read_text(encoding="utf-8"))
    fig, ax = plt.subplots(figsize=(5.2, 3.6))
    seen: dict = {}
    for k, v in sorted(fb.items(), key=lambda x: int(x[0])):
        ax.scatter(v["absorbed"], v["residue"], s=42, color=PHYS_C, alpha=.85, zorder=3)
        xy = (v["absorbed"], v["residue"])
        bump = seen.get(xy, 0)          # identical readings stagger their labels
        seen[xy] = bump + 1
        ax.annotate(f"S{k}", xy, textcoords="offset points",
                    xytext=(5 + 16 * bump, 4), fontsize=8, color=INK)
    ax.axvline(0.82, color=SELF_C, lw=0.9, ls="--", alpha=.7)
    ax.text(0.822, ax.get_ylim()[0] + .005, "known-home benchmark 0.82 [C7]",
            rotation=90, fontsize=7.5, color=SELF_C, va="bottom")
    ax.set_xlabel("absorbed (projection onto the existing map)", fontsize=9.5, color=INK)
    ax.set_ylabel("residue (novelty norm)", fontsize=9.5, color=INK)
    ax.grid(**GRID)
    style(ax)
    save(fig, "fig_residue")


if __name__ == "__main__":
    print("building the data-face figures from the banked artifacts:")
    fig_spectra()
    fig_ladders()
    fig_economics()
    fig_residue()
    print("done - every panel regenerates from this script + the committed artifacts.")
