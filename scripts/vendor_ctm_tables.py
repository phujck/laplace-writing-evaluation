def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fetch_wheel(dest: Path) -> None:
    url = WHEEL_URL
    try:
        urllib.request.urlretrieve(url, dest)  # noqa: S310 - pinned https PyPI url
    except Exception as exc:  # noqa: BLE001
        print(f"[vendor] pinned URL failed ({exc}); resolving via {PYPI_JSON_URL}")
        with urllib.request.urlopen(PYPI_JSON_URL) as fh:  # noqa: S310 - pinned https
            meta = json.load(fh)
        url = next(u["url"] for u in meta["urls"] if u["filename"] == WHEEL_NAME)
        urllib.request.urlretrieve(url, dest)  # noqa: S310 - pinned https PyPI url
    got = sha256(dest.read_bytes())
    if got != WHEEL_SHA256:
        raise SystemExit(f"[vendor] wheel checksum mismatch: {got} != {WHEEL_SHA256}")
    print(f"[vendor] wheel verified ({dest.stat().st_size / 1e6:.1f} MB) from {url}")


def demote_docstring(text: str) -> str:
    """Turn a module's leading docstring into comments so files can be concatenated."""
    match = re.match(r'^"""(.*?)"""\n', text, flags=re.DOTALL)
    if not match:
        return text
    body = "\n".join("# " + line if line else "#" for line in match.group(1).strip().splitlines())
    return body + "\n" + text[match.end():]


def apply_patches(member: str, text: str) -> str:
    for target, old, new in PATCHES:
        if target != member:
            continue
        if text.count(old) != 1:
            raise SystemExit(
                f"[vendor] patch target not found exactly once in {member}:\n{old!r}"
            )
        text = text.replace(old, new)
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--wheel", type=Path, help="vendor from a local wheel instead of PyPI")
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        wheel = Path(tmp) / WHEEL_NAME
        if args.wheel:
            shutil.copyfile(args.wheel, wheel)
            got = sha256(wheel.read_bytes())
            if got != WHEEL_SHA256:
                print(f"[vendor] ERROR: {args.wheel} is not {WHEEL_SPEC}", file=sys.stderr)
                return 1
            print(f"[vendor] using local wheel {args.wheel}")
        else:
            print(f"[vendor] downloading {WHEEL_URL}")
            fetch_wheel(wheel)

        DEST.mkdir(parents=True, exist_ok=True)
        manifest = {
            "source": {
                "spec": WHEEL_SPEC,
                "url": WHEEL_URL,
                "sha256": WHEEL_SHA256,
                "license": "MIT (c) 2019 Szymon Talaga — see LICENSE",
            },
            "generated_by": "scripts/vendor_ctm_tables.py",
            "upstream_members": {},
            "vendored": {},
        }

        with zipfile.ZipFile(wheel) as zf:
            raw = {name: zf.read(name) for name in set(MEMBERS.values()) | set(SUPPORT_MEMBERS)}
            for name, blob in sorted(raw.items()):
                manifest["upstream_members"][name] = {
                    "sha256": sha256(blob),
                    "bytes": len(blob),
                }

            outputs: dict[str, bytes] = {}
            for out_name, member in MEMBERS.items():
                blob = raw[member]
                if out_name.endswith(".py"):
                    blob = apply_patches(member, blob.decode("utf-8")).encode("utf-8")
                outputs[out_name] = blob

            support = SUPPORT_HEADER
            for member in SUPPORT_MEMBERS:
                text = apply_patches(member, raw[member].decode("utf-8"))
                support += f"\n# ---- {member} ----\n" + demote_docstring(text)
            outputs["_support.py"] = support.encode("utf-8")
            outputs["__init__.py"] = INIT_SOURCE.encode("utf-8")

        if sha256(outputs[CTM_TABLE]) != CTM_TABLE_SHA256:
            print("[vendor] ERROR: CTM table checksum mismatch", file=sys.stderr)
            return 1

        # Anything previously vendored that we no longer emit is stale by construction.
        for stale in DEST.iterdir():
            if stale.name in outputs or stale.name == "MANIFEST.json":
                continue
            shutil.rmtree(stale) if stale.is_dir() else stale.unlink()
        for name, blob in sorted(outputs.items()):
            (DEST / name).write_bytes(blob)
            manifest["vendored"][name] = {"sha256": sha256(blob), "bytes": len(blob)}
        (DEST / "MANIFEST.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")

    total = sum(v["bytes"] for v in manifest["vendored"].values())
    print(f"[vendor] DONE: {len(manifest['vendored'])} files, {total / 1e3:.1f} kB in models/ctm")
    print("[vendor] Now: git add models/ctm && git commit")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
