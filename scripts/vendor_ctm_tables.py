#!/usr/bin/env python3
"""Vendor the pybdm 0.1.0 BDM surface INTO the repo so nBDM needs no network and no pip.

The SuperARC campaign scores with `nBDM` — pybdm's normalized block decomposition
method over the CTM-B2-D12 reference table. Depending on the PyPI package would
break the repo's vendoring law (`models/README.md`: zero network, any egress
policy, fresh ephemeral container) and would drag in a 2019 wheel that imports
`pkg_resources` — removed in setuptools >= 81 and absent from uv venvs, so a bare
`import pybdm` fails outright on this repo's interpreter.

So we take the small surface instead: `bdm.py` + `partitions.py` + `encoding.py`,
their private glue (`utils.py` + `exceptions.py` + `options.py`, folded into one
generated `_support.py`), and **only** `ctm-b2-d12.pkl.gz` (23,803 bytes). The
wheel's other 39.9 MB is the b4/b5/b6/b9/d4x4 tables, which binary sequences never
touch. The `pkg_resources` resource loader is patched out on the way in — the
table is read from the vendored directory by path.

Run once (anywhere PyPI is reachable), then commit `models/ctm/`:

    python scripts/vendor_ctm_tables.py
    git add models/ctm && git commit

Re-running is idempotent: every output byte is a deterministic function of the
checksummed wheel, and each source patch asserts its target text exists, so a
changed upstream fails loudly instead of vendoring something else. Use
`--wheel <path>` to vendor from an already-downloaded wheel.

Consumer: `src/laplace/research/superarc/bdm.py` loads `models/ctm/` as a package.
"""

